/**
 * 画面の部品の詳細(`kind: detail`)の**本体の字面**(code-screen-details.ts が呼ぶ)。
 *
 * 1 件の読みの項目を `<dl>` で並べる。**この詳細に業務の判断は 1 つも無い** — 項目は `shows`(省略時は既定)、
 * 見出しは `{entity}FieldLabels`、整形は表と共有(screen-read-cells.ts)。**別クエリ由来の項目・固定文・
 * フォールバックの値・付随する併読は生成物に入れない** — 器が隣に置く手書きの部品(層 c)である。
 *
 * testid: `{部品}`(`<dl>`)/ `.{欄}`(値の `<dd>`)。アプリの語彙は 1 語も持たない(W1)。
 */

import { docComment, tsString } from '../../gen-kit/code-emit.js';
import { blockCommentText } from '../../kernel/safe-text.js';
import {
  cellExpression,
  labelExpression,
  readImportLines,
  rowInterfaceLines,
  rowInterfaceName,
  stateAttribute,
  usesTimeZone,
  usesWhen,
  whenLines,
  wordingConstLines,
} from './screen-read-cells.js';
import type { ScreenReadPlan } from './screen-read-plan.js';
import { screenTestIdsName } from './screen-form-plan.js';
import type { BodyModules } from '../body-modules.js';

/**
 * 詳細の生成物 1 本(ファイル全体の行)。
 *
 * @param plan 詳細 1 つの生成の入力
 * @param screenSpecFile 正となる画面仕様のパス(ヘッダの出どころ)
 * @param modules 本文が import する先の解決(置き場の配置が決める)
 * @returns ソースの行
 */
export function renderScreenDetailBody(plan: ScreenReadPlan, screenSpecFile: string, modules: BodyModules): readonly string[] {
  const testIds = screenTestIdsName(plan.screen);
  const name = plan.exportName;
  const timeZone = usesTimeZone(plan);
  return [
    '/**',
    ' * AUTO-GENERATED by `npm run generate` — 手編集禁止。',
    ' *',
    ' * このファイルの正は次の仕様であり、ここはその機械的な写像にすぎない。',
    ' * 変更するときは仕様を編集してから再生成すること(ADR-0006)。',
    ` *   - ${blockCommentText(screenSpecFile)}`,
    ' */',
    '',
    ...readImportLines(plan, modules),
    `import type { ScreenSkin } from '${modules.generated('screens')}';`,
    `import { ${testIds} } from '${modules.generated('testids')}';`,
    "import styles from './default.module.css';",
    '',
    docComment(['部品の testid のキー(`testids.ts` のキーと同じ。`skin` のキーでもある)。']),
    `const KEY = ${tsString(plan.path)} as const;`,
    '',
    docComment(['部品の testid(各項目の値はこれを接頭辞に持つ葉)。']),
    `const TESTID = ${testIds}[KEY];`,
    '',
    ...wordingConstLines(plan),
    ...(usesWhen(plan) ? whenLines() : []),
    ...rowInterfaceLines(plan),
    '',
    docComment([`${name} の props。`]),
    `export interface ${name}Props {`,
    '  /** 出す 1 件(読み取りの結果)。 */',
    `  readonly row: ${rowInterfaceName(plan)};`,
    ...(timeZone ? ['  /** 日時を表示するタイムゾーン(器が `displayTimeZone()` を渡す。生成物は env を読まない)。 */', '  readonly timeZone: string;'] : []),
    '  /** 器が `className` を差し替える口(渡さなければ既定のスタイル)。 */',
    `  readonly skin?: ScreenSkin<${tsString(plan.screen)}> | undefined;`,
    '}',
    '',
    docComment([
      `詳細の項目(画面 ${plan.screen} の部品 ${plan.component})。`,
      '',
      `仕様: ${screenSpecFile}`,
      '',
      '**この詳細に業務の判断は 1 つも無い。** 項目は仕様の `shows`、見出しは生成の表示名の表から来る。',
      '別クエリ由来の項目・固定文・フォールバックの値は、器が隣に置く手書きの部品である。',
      '',
      '@param props - 詳細の props',
      '@param props.row - 出す 1 件',
      ...(timeZone ? ['@param props.timeZone - 日時を表示するタイムゾーン'] : []),
      '@param props.skin - 器が className を差し替える口',
      '@returns 項目の `<dl>`',
    ]),
    `export function ${name}({ row,${timeZone ? ' timeZone,' : ''} skin }: ${name}Props) {`,
    '  return (',
    '    <dl data-testid={TESTID} className={skin?.[KEY] ?? styles.screenDetail}>',
    ...plan.columns.flatMap((column) => [
      '      <div className={styles.screenDetailRow}>',
      `        <dt className={styles.screenDetailTerm}>{${labelExpression(column, plan.source)}}</dt>`,
      `        <dd data-testid={\`\${TESTID}.${column.path}\`} ${[...stateAttribute(column, 'row'), 'className={styles.screenDetailValue}'].join(' ')}>`,
      `          {${cellExpression(column, 'row')}}`,
      '        </dd>',
      '      </div>',
    ]),
    '    </dl>',
    '  );',
    '}',
    '',
  ];
}
