/**
 * 画面の部品のフォーム(`kind: form`)の**本体の字面**(code-screen-forms.ts が呼ぶ)。
 *
 * 保存点の 1 画面フォーム(usecase-form-body.ts)と**同じ部品・同じ口**に寄せてある —— 入力欄は
 * `FormRow`、写しは `collectRow`、制約は `formOf`、送信と拒否は `ActionForm`、表示名の表は
 * `{entity}FieldLabels` / `{entity}EnumLabels`。違うのは入力の供給元(操作の入力スキーマ)と、
 * testid の根(画面が宣言した部品のキー)だけである。
 *
 * **このフォームに業務の判断は 1 つも無い**。並ぶ欄・制約・選択肢は仕様からの生成物を実行時に引き、
 * 可否は Server Action の先の実行器が持つ。アプリの語彙は 1 語も持たない(W1)—— 出てくる名前は
 * すべて引数(仕様からの導出)である。
 */

import { FORM_WORDING } from '../../messages/messages-screen.js';
import { docComment, toCamelCase, toPascalCase, tsString } from '../../gen-kit/code-emit.js';
import { blockCommentText } from '../../kernel/safe-text.js';
import type { ScreenFormPlan } from './screen-form-plan.js';
import { ERROR_LEAF, SUBMIT_LEAF, screenLabelsName, screenTestIdsName } from './screen-form-plan.js';
import { RUNTIME_FORM_MODULE, RUNTIME_RESULT_MODULE } from './runtime-modules.js';
import { ACCEPT_SAVED_STATEMENT, draftImportLines, renderDraftHandlers, renderDraftLines, renderDraftSupport } from './screen-draft.js';
import { refChoicesName, renderResolve, renderRow, renderStart, usesInitial } from './screen-form-fields.js';
import { rowKeyOf } from './screen-read-plan.js';
import type { BodyModules } from '../body-modules.js';

/** 文字列の配列リテラル(`as const`)。 */
function tuple(items: readonly string[]): string {
  return `[${items.map((item) => tsString(item)).join(', ')}] as const`;
}

/**
 * フォームの生成物 1 本(ファイル全体の行)。
 *
 * @param plan フォーム 1 つの生成の入力
 * @param screenSpecFile 正となる画面仕様のパス(ヘッダと本文コメントの出どころ)
 * @param modules 本文が import する先の解決(置き場の配置が決める)
 * @returns ソースの行
 */
export function renderScreenFormBody(plan: ScreenFormPlan, screenSpecFile: string, modules: BodyModules): readonly string[] {
  const update = plan.shape === 'update';
  const initialArg = usesInitial(plan) ? 'initial' : '';
  const name = plan.exportName;
  const checkbox = plan.controls.filter((control) => control.kind === 'checkbox').map((control) => control.field);
  const text = plan.controls.filter((control) => control.kind !== 'checkbox').map((control) => control.field);
  const testIds = screenTestIdsName(plan.screen);
  const labels = screenLabelsName(plan.screen);
  const entityCamel = toCamelCase(plan.entity);
  const refs = plan.controls.filter((control) => control.ref !== undefined);
  // 確認の器は重ね表示(S19 が宣言を要求する)。確認が要るのに重ね表示が無ければ配線を出さない(検査が先に止める)。
  const confirm = plan.confirmRequired ? plan.confirmOverlay : undefined;
  const header = [
    '/**',
    ' * AUTO-GENERATED by `npm run generate` — 手編集禁止。',
    ' *',
    ' * このファイルの正は次の仕様であり、ここはその機械的な写像にすぎない。',
    ' * 変更するときは仕様を編集してから再生成すること(ADR-0006)。',
    ` *   - ${blockCommentText(screenSpecFile)}`,
    ' */',
  ];
  return [
    "'use client';",
    '',
    ...header,
    '',
    "import { useState } from 'react';",
    ...(update ? ["import type { ReactNode } from 'react';"] : []),
    `import { ActionForm${plan.supplied.length > 0 ? ', intentOfFields' : ''} } from '${modules.component('action-runner')}';`,
    `import { ${update && checkbox.length > 0 ? 'CHECKED, ' : ''}FormRow, collectRow } from '${modules.component('form-row')}';`,
    `import type { FormChoice } from '${modules.component('form-row')}';`,
    `import { ${update ? 'changedFields, ' : ''}formOf, toFieldIssues } from '${RUNTIME_FORM_MODULE}';`,
    ...(update ? draftImportLines() : []),
    `import { ${entityCamel}FieldLabels${plan.hasEnumLabels ? `, ${entityCamel}EnumLabels` : ''} } from '${modules.generated(`${plan.entity}.labels`)}';`,
    ...(confirm === undefined ? [] : [`import { actionAttributesFor } from '${modules.generated('action-attributes')}';`]),
    `import { operationInputSchemas } from '${modules.generated('operation-inputs')}';`,
    ...[...new Set(refs.map((control) => control.ref?.entity ?? ''))].map(
      (entity) => `import type { ${toPascalCase(entity)}Row } from '${modules.generated(`${entity}.schema`)}';`,
    ),
    `import type { ScreenSkin } from '${modules.generated('screens')}';`,
    `import { ${plan.label === undefined && confirm?.labelKey === undefined ? '' : `${labels}, `}${testIds} } from '${modules.generated('testids')}';`,
    `import type { ActionResult, FieldIssue } from '${RUNTIME_RESULT_MODULE}';`,
    "import type { z } from 'zod';",
    "import styles from './default.module.css';",
    '',
    docComment(['載せる操作の入力スキーマ(生成 zod。サーバー側の検証と同じもの)。']),
    `const SCHEMA = operationInputSchemas[${tsString(plan.action)}];`,
    '',
    docComment(['操作の入力。']),
    'type Input = z.infer<typeof SCHEMA>;',
    '',
    docComment(['入力欄の制約(生成 zod からの導出)。']),
    'const FORM = formOf(SCHEMA);',
    '',
    docComment(['部品の testid のキー(`testids.ts` のキーと同じ。`skin` のキーでもある)。']),
    `const KEY = ${tsString(plan.path)} as const;`,
    '',
    docComment(['部品の testid(入力欄・送信ボタン・拒否の表示はこれを接頭辞に持つ葉)。']),
    `const TESTID = ${testIds}[KEY];`,
    '',
    ...(plan.label === undefined
      ? []
      : [docComment(['部品の表示名(仕様の `label`。見出しと送信ボタンの文言)。']), `const TITLE = ${labels}[KEY];`, '']),
    ...(confirm === undefined
      ? []
      : [
          docComment(['確認の器(重ね表示)の testid。仕様の overlays が宣言した確認ダイアログの器と中身(実行 / やめる)。']),
          `const CONFIRM_DIALOG = ${testIds}[${tsString(confirm.dialog)}];`,
          `const CONFIRM_BAR = ${testIds}[${tsString(confirm.bar)}];`,
          '',
          docComment(['確認の見出しと実行ボタンの文言(重ね表示の `label`。無ければ送信ボタンの文言)。']),
          `const CONFIRM_LABEL = ${confirm.labelKey === undefined ? submitLabelSource(plan) : `${labels}[${tsString(confirm.labelKey)}]`};`,
          '',
          docComment(['送信前の確認の文言(`{見出し}。{注意書き}`。注意書きは生成物 `action-attributes` から引く)。']),
          `const CONFIRM_MESSAGE = \`\${CONFIRM_LABEL}。\${actionAttributesFor(${tsString(plan.action)}).confirmNotes.join('')}\`;`,
          '',
        ]),
    docComment(['器が `initial` で渡す欄(参照・識別子)。入力欄は出さない。']),
    `const SUPPLIED = ${tuple(plan.supplied)};`,
    '',
    docComment(['文字列・数値・選択で入力する欄(entity_spec の宣言の順)。']),
    `const TEXT_FIELDS = ${tuple(text)};`,
    '',
    docComment(['チェックボックスで入力する欄。']),
    `const FLAG_FIELDS = ${tuple(checkbox)};`,
    '',
    ...(refs.length === 0
      ? []
      : [
          docComment(['参照の欄の選択肢の先頭(値を選ばない選択肢)の既定の語。`emptyOptionLabel` で欄ごとに言い換えられる。']),
          `const NONE_SELECTED = ${tsString(FORM_WORDING.none_selected())};`,
          '',
        ]),
    ...refs.flatMap((control) => refOptionLines(control)),
    docComment([`${name} の props。`]),
    `export interface ${name}Props {`,
    '  /** 呼び出す Server Action(生成物。器が渡す — 画面の部品の生成物は `_actions` を import しない)。 */',
    '  readonly action: (input: Input) => Promise<ActionResult<unknown>>;',
    ...(update
      ? [
          '  /** 器が決める値(編集の対象の識別子と、いまの値。操作の入力と同じ型 — 入力欄の文字列への写しは生成物が持つ)。 */',
          '  readonly initial?: Readonly<Partial<Input>> | undefined;',
        ]
      : [
          '  /** 器が決める値(参照の欄)。鍵は欄の名前。 */',
          '  readonly initial?: Readonly<Record<string, string>> | undefined;',
        ]),
    ...(update
      ? [
          '  /** 編集してよい欄(`writableFields` の結果)。省略すると入力スキーマの欄すべて。 */',
          '  readonly writable?: readonly string[] | undefined;',
        ]
      : []),
    ...refs.flatMap((control) => [
      `  /** 参照の欄 ${control.field} の選択肢の行(仕様の \`reads\` の読みの結果。生成物が選択肢にする)。 */`,
      `  readonly options?: readonly ${refOptionName(control.field)}[] | undefined;`,
    ]),
    ...(refs.length === 0
      ? []
      : [
          '  /** 参照の欄の「選ばない」選択肢の文言(欄ごとの上書き。省略した欄は既定の語)。鍵は参照の欄の名前。 */',
          `  readonly emptyOptionLabel?: Readonly<Partial<Record<${refs.map((control) => tsString(control.field)).join(' | ')}, string>>> | undefined;`,
        ]),
    '  /** 欄ごとの選択肢(器が読み取り経路などから決めて渡す。ある欄は選択欄として描く)。鍵は欄の名前。 */',
    '  readonly choices?: Readonly<Record<string, readonly FormChoice[]>> | undefined;',
    '  /** 器が `className` を差し替える口(渡さなければ既定のスタイル)。 */',
    `  readonly skin?: ScreenSkin<${tsString(plan.screen)}> | undefined;`,
    '  /** 成功したときの追加の副作用(遷移はここで書かない — 決めるのは仕様の `navigations`)。 */',
    '  readonly onSuccess?: (() => void) | undefined;',
    '}',
    '',
    docComment(['入力欄の初期値(参照・識別子は器が渡す値、選択欄はスキーマの先頭の選択肢、それ以外は空)。']),
    ...renderStart(plan),
    '',
    ...(update ? renderDraftSupport() : []),
    docComment([
      `操作 ${plan.action} のフォーム(画面 ${plan.screen} の部品 ${plan.component})。`,
      '',
      `仕様: ${screenSpecFile}`,
      '',
      '**このフォームに業務の判断は 1 つも無い。** 並ぶ欄は操作の入力そのもので、制約は生成 zod から、',
      '表示名は生成の表から来る。可否の判断は Server Action の先の実行器が持つ。',
      '',
      '@param props - フォームの props',
      '@param props.action - 呼び出す Server Action',
      ...(usesInitial(plan) ? ['@param props.initial - 器が決める値'] : []),
      ...(update ? ['@param props.writable - 編集してよい欄'] : []),
      ...(refs.length === 0 ? [] : ['@param props.options - 参照の欄の選択肢の行', '@param props.emptyOptionLabel - 参照の欄の「選ばない」選択肢の文言']),
      '@param props.choices - 欄ごとの選択肢',
      '@param props.skin - 器が className を差し替える口',
      '@param props.onSuccess - 成功したときの追加の副作用',
      '@returns 入力欄と送信ボタン',
    ]),
    `export function ${name}({ action,${usesInitial(plan) ? ' initial = {},' : ''}${update ? ' writable,' : ''}${refs.length === 0 ? '' : ' options, emptyOptionLabel,'} choices, skin, onSuccess }: ${name}Props) {`,
    ...(update
      ? [
          '  const shown = (field: string): boolean => writable === undefined || writable.includes(field);',
          // 2 層の入力(baseline / values)。送るのは**baseline と違う欄だけ**(部分更新)。変更が無いあいだは送信ボタンを押せなくする。
          ...renderDraftLines('initial'),
          '',
          ...renderDraftHandlers(),
        ]
      : [`  const [values, setValues] = useState<Record<string, string>>(() => startValues(${initialArg}));`]),
    '',
    ...renderResolve(plan),
    '',
    '  return (',
    '    <section data-testid={TESTID} className={skin?.[KEY] ?? styles.screenForm}>',
    ...(plan.label === undefined ? [] : ['      <h2 className={styles.screenFormTitle}>{TITLE}</h2>']),
    '      <ActionForm',
    '        action={action}',
    `        event={${tsString(plan.action)}}`,
    `        errorTestId={\`\${TESTID}.${ERROR_LEAF}\`}`,
    `        fieldLabels={${entityCamel}FieldLabels}`,
    ...(update ? [] : ['        onSuccess={() => {', `          setValues(startValues(${initialArg}));`, '          onSuccess?.();', '        }}']),
    // 成功のあとは `onSuccess` → `refresh()` の順(runner-core.ts)。送った値を保存済みの値として覚える(`sentValues` の doc)。
    ...(update
      ? [
          '        onSuccess={(_, sent) => {',
          `          ${ACCEPT_SAVED_STATEMENT};`,
          '          onSuccess?.();',
          '        }}',
        ]
      : []),
    '        resolve={resolve}',
    // 送信の意図を名指すのは器が渡す欄(`SUPPLIED`)だけ —— 利用者が入れる欄(選ぶ参照の `_id` を含む)を直した押し直しは
    // 同じ鍵のまま `resend_input_mismatch` で断られる(点検 22 回目 B22-1。名指しの本体は部品の `intentOfFields`)。
    ...(plan.supplied.length > 0 ? ['        intentOf={(input) => intentOfFields(input, SUPPLIED)}'] : []),
    ...(confirm === undefined
      ? []
      : [
          '        confirm={{',
          '          dialogTestId: CONFIRM_DIALOG,',
          '          confirmBarTestId: CONFIRM_BAR,',
          '          message: CONFIRM_MESSAGE,',
          '          confirmLabel: CONFIRM_LABEL,',
          '        }}',
        ]),
    '      >',
    '        {({ phase }) => (',
    '          <>',
    ...plan.controls.flatMap((control) => renderRow(plan, control, update)),
    `            <button data-testid={\`\${TESTID}.${SUBMIT_LEAF}\`} className={styles.screenFormSubmit} type="submit" disabled={${update ? "phase === 'pending' || changed.length === 0 || view.conflicts.length > 0" : "phase === 'pending'"}}>`,
    `              {phase === 'pending' ? ${tsString(FORM_WORDING.pending())} : ${submitLabelSource(plan)}}`,
    '            </button>',
    '          </>',
    '        )}',
    '      </ActionForm>',
    '    </section>',
    '  );',
    '}',
    '',
  ];
}

/** 送信ボタン(と確認ダイアログの実行ボタン)の文言の式(`label` があればそれ、無ければ既定の語)。 */
function submitLabelSource(plan: ScreenFormPlan): string {
  return plan.label === undefined ? tsString(FORM_WORDING.submit()) : 'TITLE';
}

/** 参照の欄の選択肢の行の型の名前。 */
function refOptionName(field: string): string {
  return `${toPascalCase(field)}Option`;
}

/** 参照の欄 1 つの選択肢の行の型と、選択肢を作る関数(未選択 + 読みの行)。 */
function refOptionLines(control: ScreenFormPlan['controls'][number]): readonly string[] {
  const ref = control.ref;
  if (ref === undefined) return [];
  const row = `${toPascalCase(ref.entity)}Row`;
  const label = rowKeyOf(ref.labelField);
  return [
    docComment([`参照の欄 ${control.field} の選択肢の行(読みの projection の \`id\` と表示名。値の型の正は生成 zod の行の型)。`]),
    `export interface ${refOptionName(control.field)} {`,
    `  readonly id: ${row}['id'];`,
    `  readonly ${label}: ${row}[${tsString(ref.labelField)}];`,
    '}',
    '',
    docComment([
      `参照の欄 ${control.field} の選択肢(未選択 + 読みの行。${ref.required ? '必須の欄は未選択のままでは送れない' : '値を選ばないことが許される欄'})。`,
    ]),
    `function ${refChoicesName(control.field)}(options: readonly ${refOptionName(control.field)}[] | undefined, emptyLabel: string | undefined): readonly FormChoice[] {`,
    `  return [{ value: '', label: emptyLabel ?? NONE_SELECTED }, ...(options ?? []).map((option) => ({ value: option.id, label: option.${label} }))];`,
    '}',
    '',
  ];
}
