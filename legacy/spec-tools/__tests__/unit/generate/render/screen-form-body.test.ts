/**
 * 画面の部品のフォーム(`kind: form`)の本体の字面(screen-form-body.ts)と、
 * 生成の入力の導出(screen-form-plan.ts)のテスト。
 *
 * 確かめるのは「作成は欄を全部並べて 1 回で送る」「編集は変わった欄だけを送る」「testid の根は
 * 部品のキーで、葉は欄の名前・submit・error」「表示名の表が無い集約は欄の名前を出す」「手書きの器が
 * 差し替える口(skin)がある」ことである。アプリの語彙は 1 語も使わない(W1)。
 */

