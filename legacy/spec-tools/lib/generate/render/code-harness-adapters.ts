/**
 * ハーネスの**アダプタ 6 本**(置き場の配置の役割 `harness-adapter` 4 本 / `save-harness-adapter` 2 本。Next.js なら
 * `infrastructure/__tests__/{rls,eq}-{world,expect}.ts` / `composition/__tests__/eq-save-{world,expect}.ts`)の生成器(束 ①-d 手 2)。
 *
 * ## なぜ生成物なのか
 *
 * ハーネス本体は実行時パッケージ(`@kaninabe/runtime/testing/**`。ADR-0013)に住み、製品側に残るのは
 * 「製品の生成物と口(`HarnessPorts`)を束ねて渡す」配線だけになった(束 ①-d 手 1)。その配線は
 * **宣言から一意に決まる**——渡すものは製品の生成物であり、置き場は仕組みが決めているパスである。
 * 手で書き写す限り、次の製品を立てる人が同じ 6 本を写経することになり、写経が残っているあいだは
 * 「仕組みを借りている」状態が続く(通し実行は一時ツリーへこの 6 本を写していた)。
 *
 * 生成物にすると:
 *   - fixture(題材)の一時ツリーでも `npm run generate` が同じ 6 本を書き出すので、**通し実行の写しが
 *     消える**(残るのは口の実装 1 本で、それは製品の接続層である)。
 *   - 生成テスト 83 本の import 先は**変わらない** —— 呼ばれる場所を動かさないのがアダプタの役目である。
 *
 * ## 何を渡すか(製品ごとに変わるもの)
 *
 * 出力先のパスだけが製品の宣言(`product.md` の `roots.app`)から来る。中身は仕組みの形であり、
 * **アプリの語彙は 1 語も無い**(集約名・ロール名・列名は設計図が運ぶ)。
 *
 * 規約どおりファイル I/O はしない純粋関数(scripts-code-quality.md)。
 */

import type { SpecModel } from '../../model/types.js';
import type { DocGenerator, GeneratedSection, GenerateContext } from '../../gen-kit/generator.js';
import { PRODUCT_DECL_FILE } from '../../io/paths.js';
import type { ProductLayout } from '../../model/product/layout.js';
import type { ProductRoots } from '../../model/product/types.js';
import { testPlacerOf } from './test-placement.js';
import type { GeneratedTestRole } from './test-placement.js';
import { EQ_WORLD_ADAPTER, eqExpectAdapter } from './harness-adapter-eq.js';
import { EQ_SAVE_WORLD_ADAPTER, eqSaveExpectAdapter } from './harness-adapter-save.js';
import { rlsExpectAdapter, rlsWorldAdapter } from './harness-adapter-rls.js';
import { bodyModulesOf } from '../body-modules.js';
import type { BodyModules } from '../body-modules.js';

/** アダプタ 1 本の宣言(置き場と本文)。 */
interface HarnessAdapter {
  /** 置き場の役割(基盤の層に置くか、保存点の一致の証明が使う配線の層に置くか。層の名前も綴りも配置が持つ)。 */
  readonly placement: Extract<GeneratedTestRole, 'harness-adapter' | 'save-harness-adapter'>;
  /** アダプタの名前(置き場のキー)。 */
  readonly name: string;
  /** 何のアダプタか(ヘッダの 1 行)。 */
  readonly role: string;
  /** 本文(`import 'server-only';` とヘッダは生成器が付ける)。import する先は置き場の配置から引いた解決を受け取る。 */
  readonly body: (modules: BodyModules) => readonly string[];
}

/**
 * 生成するアダプタの全数(**これ以外は無い**)。
 *
 * 6 本が 3 対に分かれているのは、実行する単位が 3 つ(RLS の挙動 / 単発の操作の一致 /
 * 保存点の一致)あるからである。対の中は「world の作り方」と「表明」の 2 本である。
 */
const ADAPTERS: readonly HarnessAdapter[] = [
  {
    placement: 'harness-adapter',
    name: 'rls-world',
    role: 'RLS の挙動テストの**world の作り方**に口を渡すアダプタ',
    body: rlsWorldAdapter,
  },
  {
    placement: 'harness-adapter',
    name: 'rls-expect',
    role: 'RLS の挙動テストの**表明**に口とロールの根拠を渡すアダプタ',
    body: rlsExpectAdapter,
  },
  {
    placement: 'harness-adapter',
    name: 'eq-world',
    role: 'engine ⇔ RPC の一致の証明の**world の作り方**に口を渡すアダプタ',
    body: () => EQ_WORLD_ADAPTER,
  },
  {
    placement: 'harness-adapter',
    name: 'eq-expect',
    role: 'engine ⇔ RPC の一致の証明の**表明**に口と実行計画を渡すアダプタ',
    body: eqExpectAdapter,
  },
  {
    placement: 'save-harness-adapter',
    name: 'eq-save-world',
    role: '保存点の一致の証明の**world の使い方**(作り方は単発と同じ 1 本)',
    body: () => EQ_SAVE_WORLD_ADAPTER,
  },
  {
    placement: 'save-harness-adapter',
    name: 'eq-save-expect',
    role: '保存点の一致の証明の**表明**に口と 4 つの宣言を渡すアダプタ',
    body: eqSaveExpectAdapter,
  },
];

/**
 * アダプタ 1 本のヘッダ。
 *
 * **正は仕様ファイルではない** —— このファイルが写しているのは「ハーネスの口(`HarnessPorts`)と
 * 製品の生成物の配線」であり、仕様の写像ではない。だから出どころは仕様ではなくその 2 つを示す。
 *
 * @param role 何のアダプタか
 * @returns ヘッダの行
 */
function headerOf(role: string): readonly string[] {
  return [
    '/**',
    ' * AUTO-GENERATED by `npm run generate` — 手編集禁止。',
    ' *',
    ` * ${role}。`,
    ' *',
    ' * **ハーネス本体は実行時パッケージに住む**(`@kaninabe/runtime/testing/**`。ADR-0013)。ここは',
    ' * 製品の生成物と口(`HarnessPorts`)を束ねて渡すだけの配線であり、**生成テストの import 先を',
    ' * 動かさない**ために同じパスに置いてある。口の実装(`harness-ports.ts`)だけが手書きで、',
    ' * そこが製品の接続層(実 DB とセッションに触る手)を知る唯一の場所である。',
    ' */',
  ];
}

/** アダプタ 6 本を製品の木に書き出すジェネレーター。 */
export const harnessAdaptersGenerator: DocGenerator = {
  id: 'code-harness-adapters',

  generate(_model: SpecModel, ctx: GenerateContext): GeneratedSection[] {
    return harnessAdapterSections(ctx.roots, ctx.layout);
  },
};

/**
 * アダプタ 6 本のセクションを組む(実装の木を持たない製品では 0 本)。置き場は配置の役割(`harness-adapter` / `save-harness-adapter`)が決める。
 *
 * @param roots 製品が宣言した根
 * @param layout 置き場の配置(アプリの枠の後段が与える)
 * @returns 生成するファイル(宣言順)
 */
export function harnessAdapterSections(roots: ProductRoots, layout: ProductLayout): GeneratedSection[] {
  return ADAPTERS.flatMap((adapter) => {
    const origin = { what: `ハーネスのアダプタ ${adapter.name}`, location: { file: PRODUCT_DECL_FILE, pointer: 'roots.app' } };
    const place = testPlacerOf(layout, roots, adapter.placement, origin);
    if (place === null) return [];
    return [
      {
        file: place(adapter.name),
        content: [...headerOf(adapter.role), "import 'server-only';", ...adapter.body(bodyModulesOf({ layout, roots }, origin)), ''].join('\n'),
        wholeFile: true,
      },
    ];
  });
}
