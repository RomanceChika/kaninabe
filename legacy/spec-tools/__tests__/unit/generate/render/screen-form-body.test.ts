describe('参照の欄の選択肢(kind: form の reads)', () => {
  const ref = (required: boolean) => ({ entity: 'venue', labelField: 'name', required });
  const text = source(
    createPlan({
      supplied: [],
      hasEnumLabels: false,
      controls: [
        { field: 'name', kind: 'text' },
        { field: 'venue_id', kind: 'select', ref: ref(false) },
      ],
    }),
  );

  it('参照の欄は選択欄になり、選択肢は器が渡す options(読みの行)から生成物が作る(先頭は未選択)', () => {
    expect(text).toContain("import type { VenueRow } from '@/domain/generated/venue.schema';");
    expect(text).toContain("const NONE_SELECTED = '未選択';");
    expect(text).toContain('export interface VenueIdOption {');
    expect(text).toContain("readonly name: VenueRow['name'];");
    expect(text).toContain('readonly options?: readonly VenueIdOption[] | undefined;');
    expect(text).toContain("return [{ value: '', label: emptyLabel ?? NONE_SELECTED }, ...(options ?? []).map((option) => ({ value: option.id, label: option.name }))];");
    expect(text).toContain("choices={venueIdChoices(options, emptyOptionLabel?.['venue_id'])}");
    // 「選ばない」選択肢の語は器が欄ごとに言い換えられる(既定は NONE_SELECTED)。
    expect(text).toContain("readonly emptyOptionLabel?: Readonly<Partial<Record<'venue_id', string>>> | undefined;");
    expect(text).toContain('options, emptyOptionLabel, choices, skin, onSuccess }');
  });

  it('参照の選択欄は enum の表示名の表を引かず、器の choices では上書きされない(ref 以外の欄だけが choices を引く)', () => {
    expect(text).not.toContain('optionLabels={sampleEnumLabels.venue_id}');
    expect(text).not.toContain("choices={choices?.['venue_id']}");
    expect(text).toContain("choices={choices?.['name']}");
    expect(text).not.toContain('EnumLabels');
  });

  it('必須の参照の欄も同じ形(必須は未選択のままでは送れないことを doc に書く)', () => {
    const required = source(
      createPlan({ supplied: [], hasEnumLabels: false, controls: [{ field: 'venue_id', kind: 'select', ref: ref(true) }] }),
    );

    expect(required).toContain('必須の欄は未選択のままでは送れない');
    expect(required).toContain("choices={venueIdChoices(options, emptyOptionLabel?.['venue_id'])}");
  });

  it('参照の欄が無いフォームは options も NONE_SELECTED も出さない', () => {
    expect(source(createPlan())).not.toContain('readonly options?');
    expect(source(createPlan())).not.toContain('NONE_SELECTED');
  });
});

