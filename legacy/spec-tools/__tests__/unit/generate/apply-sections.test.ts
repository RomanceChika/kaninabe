/**
 * `applyGeneratedSections`(生成セクションの書き込みループ)のユニットテスト。
 *
 * BACKLOG「新プロジェクト初期化時の空仕様で generate が成立する」への対応。
 * マーカー差し込みモードの対象ファイルが無いとき(新規プロジェクトでは
 * `specs/{backend,frontend}/**\/README.md` のような一覧の置き場をまだ手で作っていないのが
 * 普通)に ENOENT で落ちず、書き込みを飛ばして完走することを実ファイルシステムで確かめる。
 */

import { mkdtempSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import {
  applyGeneratedSections,
  findOrphanGenerated,
  findStrayInBook,
  findUndeclaredInGeneratedDir,
} from '../../../lib/generate/apply-sections.js';
import type { FileSection } from '../../../lib/generate/apply-sections.js';
import { isolatedGit } from '../../helpers/git-env.js';

/** 書いてよい木(この単体テストが使う相対パスを含む)。 */
const TREES = ['specs', 'app'];

let root: string;

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'apply-sections-'));
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

describe('applyGeneratedSections', () => {
  it('マーカー差し込み先のファイルが無ければ ENOENT で落ちず、書き込みを飛ばす(空プロジェクトの既定状態)', () => {
    const byFile = new Map<string, readonly FileSection[]>([
      ['specs/backend/queries/README.md', [{ marker: 'query-list', content: '(空)' }]],
    ]);
    const logs: string[] = [];

    const result = applyGeneratedSections(byFile, root, { check: false, trees: TREES }, (line) => logs.push(line));

    expect(result.written).toEqual([]);
    expect(result.skipped).toEqual(['specs/backend/queries/README.md']);
    expect(logs.some((line) => line.includes('specs/backend/queries/README.md') && line.includes('無いため'))).toBe(
      true,
    );
  });

  it('マーカー差し込み先のファイルがあれば置き換えて書く', () => {
    const relative = 'specs/backend/queries/README.md';
    mkdirSync(join(root, 'specs/backend/queries'), { recursive: true });
    writeFileSync(
      join(root, relative),
      ['# クエリ一覧', '', '<!-- AUTO-GENERATED:query-list -->', '(旧)', '<!-- /AUTO-GENERATED:query-list -->', ''].join(
        '\n',
      ),
    );
    const byFile = new Map<string, readonly FileSection[]>([
      [relative, [{ marker: 'query-list', content: '(新)' }]],
    ]);

    const result = applyGeneratedSections(byFile, root, { check: false, trees: TREES });

    expect(result.written).toEqual([relative]);
    expect(readFileSync(join(root, relative), 'utf-8')).toContain('(新)');
  });

  it('ファイル全体モードは対象が無くても新規に作る', () => {
    const relative = 'app/src/domain/generated/example.ts';
    const byFile = new Map<string, readonly FileSection[]>([
      [relative, [{ content: 'export const x = 1;\n', wholeFile: true }]],
    ]);

    const result = applyGeneratedSections(byFile, root, { check: false, trees: TREES });

    expect(result.written).toEqual([relative]);
    expect(readFileSync(join(root, relative), 'utf-8')).toBe('export const x = 1;\n');
  });

  it('check モードは書き込まず、差分があるファイルを stale として報告する', () => {
    const relative = 'app/src/domain/generated/example.ts';
    mkdirSync(join(root, 'app/src/domain/generated'), { recursive: true });
    writeFileSync(join(root, relative), 'export const x = 0;\n');
    const byFile = new Map<string, readonly FileSection[]>([
      [relative, [{ content: 'export const x = 1;\n', wholeFile: true }]],
    ]);

    const result = applyGeneratedSections(byFile, root, { check: true, trees: TREES });

    expect(result.stale).toEqual([relative]);
    expect(result.written).toEqual([]);
    expect(readFileSync(join(root, relative), 'utf-8')).toBe('export const x = 0;\n');
  });
});

describe('findOrphanGenerated(宣言から出ない生成ファイルの検出)', () => {
  // 検出の本体(`lib` の `git ls-files`)は環境を継ぐ。親の `GIT_` は setupFiles の先頭の止めがワーカーの環境から先に全部消すので、
  // フックの中で動かしても使い捨てリポジトリを見る(準備側は `isolatedGit`。点検 24 回目 O24-3)。

  /** 一時ディレクトリを本物の git リポジトリにし、`tracked` だけをコミット済みにする。 */
  function repoWith(files: Readonly<Record<string, string>>, tracked: readonly string[]): void {
    mkdirSync(join(root, 'supabase/migrations'), { recursive: true });
    for (const [file, content] of Object.entries(files)) writeFileSync(join(root, file), content);
    const git = (...args: readonly string[]): void => {
      isolatedGit(root, args);
    };
    git('init', '-q');
    git('config', 'user.email', 'test@example.com');
    git('config', 'user.name', 'test');
    if (tracked.length === 0) return;
    git('add', ...tracked);
    git('-c', 'commit.gpgsign=false', 'commit', '-qm', 'tracked');
  }

  const header = '-- AUTO-GENERATED by `npm run generate` — 手編集禁止。\n';

  it('宣言から出ない未追跡の生成ファイルを余分として返す(採番をやり直したときの取り残し)', () => {
    repoWith(
      {
        'supabase/migrations/001_rpc_insert_x.sql': `${header}create or replace function api.insert_x();`,
        'supabase/migrations/002_rpc_insert_x.sql': `${header}create or replace function api.insert_x();`,
      },
      [],
    );

    const orphans = findOrphanGenerated(root, 'supabase/migrations', new Set(['supabase/migrations/002_rpc_insert_x.sql']));

    expect(orphans).toEqual(['supabase/migrations/001_rpc_insert_x.sql']);
  });

  it('追跡済み(適用済みの歴史)の生成ファイルは余分にしない —— 名前を新しくする規則と衝突させない', () => {
    repoWith(
      { 'supabase/migrations/001_rpc_insert_x.sql': `${header}create or replace function api.insert_x();` },
      ['supabase/migrations/001_rpc_insert_x.sql'],
    );

    expect(findOrphanGenerated(root, 'supabase/migrations', new Set())).toEqual([]);
  });

  it('AUTO-GENERATED ヘッダを持たない手書きの migration は余分にしない', () => {
    repoWith({ 'supabase/migrations/001_handwritten.sql': 'create table public.x ();' }, []);

    expect(findOrphanGenerated(root, 'supabase/migrations', new Set())).toEqual([]);
  });

  it('git が使えない置き場では警告を出して検出をスキップする(fail-open を宣言する)', () => {
    mkdirSync(join(root, 'supabase/migrations'), { recursive: true });
    writeFileSync(join(root, 'supabase/migrations/001_rpc_insert_x.sql'), `${header}select 1;`);
    const logs: string[] = [];

    const orphans = findOrphanGenerated(root, 'supabase/migrations', new Set(), (line) => logs.push(line));

    expect(orphans).toEqual([]);
    expect(logs.some((line) => line.includes('git が使えない'))).toBe(true);
  });
});

describe('findStrayInBook(本の根の下の宣言の無いファイル。点検 13 回目 C13-7)', () => {
  const book = 'docs/book';
  const previews = 'docs/book/assets/previews';

  it('宣言の無いファイルを深さを問わず名指す(拡張子と隠しファイルも問わない)', () => {
    mkdirSync(join(root, book, 'spec'), { recursive: true });
    writeFileSync(join(root, book, 'index.html'), 'x');
    writeFileSync(join(root, book, 'stray.html'), '<script>1</script>');
    writeFileSync(join(root, book, 'spec', 'old.html'), 'x');
    writeFileSync(join(root, book, '.env'), 'x');

    expect(findStrayInBook(root, book, new Set([`${book}/index.html`]), null)).toEqual([`${book}/.env`, `${book}/spec/old.html`, `${book}/stray.html`]);
  });

  it('プレビューの置き場は製品の入力なので外す(隣の資材は見る)', () => {
    mkdirSync(join(root, previews), { recursive: true });
    writeFileSync(join(root, previews, 'a.html'), 'x');
    writeFileSync(join(root, book, 'assets', 'stray.js'), 'x');

    expect(findStrayInBook(root, book, new Set(), previews)).toEqual([`${book}/assets/stray.js`]);
  });

  it('二値の写しは閉じた行だけを外す(同じ置き場の別の png は赤)', () => {
    mkdirSync(join(root, book, 'assets'), { recursive: true });
    writeFileSync(join(root, book, 'assets', 'brand-icon.png'), 'x');
    writeFileSync(join(root, book, 'assets', 'other.png'), 'x');

    expect(findStrayInBook(root, book, new Set(), null)).toEqual([`${book}/assets/other.png`]);
  });

  it('リンクも数える(通常のファイルだけを見ない)', () => {
    mkdirSync(join(root, book), { recursive: true });
    symlinkSync('/etc/hosts', join(root, book, 'link.html'));

    expect(findStrayInBook(root, book, new Set(), null)).toEqual([`${book}/link.html`]);
  });

  it('本の根が無ければ何も無い', () => {
    expect(findStrayInBook(root, book, new Set(), null)).toEqual([]);
  });
});

describe('findUndeclaredInGeneratedDir(置き場ぜんたいが生成物のときの余分の検出)', () => {
  /** 結果表の元データの置き場(中身は全部が生成物)。 */
  const dir = 'docs/book/assets/results';

  it('宣言集合に無いファイルを余分として報告する(集約をリネームしたときの取り残し)', () => {
    mkdirSync(join(root, dir), { recursive: true });
    writeFileSync(join(root, dir, 'entry.json'), '{}');
    writeFileSync(join(root, dir, 'zz_renamed.json'), '{}');

    expect(findUndeclaredInGeneratedDir(root, dir, new Set([`${dir}/entry.json`]))).toEqual([
      `${dir}/zz_renamed.json`,
    ]);
  });

  it('**目印を見ない**(JSON はコメントを書けないので AUTO-GENERATED の行を持てない)', () => {
    mkdirSync(join(root, dir), { recursive: true });
    writeFileSync(join(root, dir, 'entry.json'), '{"cases": []}');

    expect(findUndeclaredInGeneratedDir(root, dir, new Set())).toEqual([`${dir}/entry.json`]);
  });

  it('置き場そのものが無ければ余分は無い(その種の宣言を 1 つも持たないアプリ)', () => {
    expect(findUndeclaredInGeneratedDir(root, dir, new Set())).toEqual([]);
  });
});
