/**
 * 画面の部品の表(`kind: table`)の**本体の字面**(code-screen-tables.ts が呼ぶ)。
 *
 * 読むだけの表。**この表に業務の判断は 1 つも無い** — 列は `shows`(省略時は既定)、見出しは
 * `{entity}FieldLabels`、セルの整形は表と詳細で共有(screen-read-cells.ts)、行が 0 件のときの表示(空の葉)も
 * 既定の 1 形で生成物が持つ。行のリンクは生成物が `screenRoutes` と行の `id` から自分で組む。器(手書き)は行・`timeZone`・必要なら
 * `rowExtras`(行ごとに末尾の列へ手書きの部品を差し込む口)を渡して置くだけである。
 *
 * testid: `{部品}`(外側)/ `.row` / `.column.{欄}`(見出し)/ `.empty`。アプリの語彙は 1 語も持たない(W1)。
 */

import { TABLE_WORDING } from '../../messages/messages-screen.js';
import { docComment, tsString } from '../../gen-kit/code-emit.js';
import { blockCommentText } from '../../kernel/safe-text.js';
import { hasRowLink, ROW_EXTRA_HEADER_LINES, rowExtraCellLine, rowExtrasPropLines, rowHrefLines, rowLinkConstLines, rowLinkImportLines } from './screen-row-slots.js';
import {
  cellExpression,
  labelExpression,
  readImportLines,
  rowInterfaceLines,
  ROW_KEY_FIELD,
  rowInterfaceName,
  stateAttribute,
  usesTimeZone,
  usesWhen,
  whenLines,
  wordingConstLines,
} from './screen-read-cells.js';
import { COLUMN_LEAF, EMPTY_LEAF, ROW_LEAF, rowKeyOf } from './screen-read-plan.js';
import type { ScreenReadPlan } from './screen-read-plan.js';
import { screenLabelsName, screenTestIdsName } from './screen-form-plan.js';
import type { BodyModules } from '../body-modules.js';

/** 手書きしない旨のヘッダ(操作を持つ表・ボタン列の生成物も同じ)。 */
export function headerLines(screenSpecFile: string): readonly string[] {
  return [
    '/**',
    ' * AUTO-GENERATED by `npm run generate` — 手編集禁止。',
    ' *',
    ' * このファイルの正は次の仕様であり、ここはその機械的な写像にすぎない。',
    ' * 変更するときは仕様を編集してから再生成すること(ADR-0006)。',
    ` *   - ${blockCommentText(screenSpecFile)}`,
    ' */',
  ];
}

/**
 * 表の生成物 1 本(ファイル全体の行)。
 *
 * @param plan 表 1 つの生成の入力
 * @param screenSpecFile 正となる画面仕様のパス(ヘッダの出どころ)
 * @param modules 本文が import する先の解決(置き場の配置が決める)
 * @returns ソースの行
 */
export function renderScreenTableBody(plan: ScreenReadPlan, screenSpecFile: string, modules: BodyModules): readonly string[] {
  const testIds = screenTestIdsName(plan.screen);
  const labels = screenLabelsName(plan.screen);
  const name = plan.exportName;
  const row = rowInterfaceName(plan);
  const timeZone = usesTimeZone(plan);
  const linked = hasRowLink(plan);
  const first = plan.columns[0]?.path;
  const header = plan.columns.map((column) => [
    `              <th data-testid={\`\${TESTID}.${COLUMN_LEAF}.${column.path}\`} className={styles.screenTableHead}>`,
    `                {${labelExpression(column, plan.source)}}`,
    '              </th>',
  ]);
  return [
    ...headerLines(screenSpecFile),
    '',
    "import type { ReactNode } from 'react';",
    ...rowLinkImportLines(plan, modules),
    ...readImportLines(plan, modules),
    `import type { ScreenSkin } from '${modules.generated('screens')}';`,
    `import { ${plan.label === undefined ? '' : `${labels}, `}${testIds} } from '${modules.generated('testids')}';`,
    "import styles from './default.module.css';",
    '',
    docComment(['部品の testid のキー(`testids.ts` のキーと同じ。`skin` のキーでもある)。']),
    `const KEY = ${tsString(plan.path)} as const;`,
    '',
    docComment(['部品の testid(行・見出し・空の表示はこれを接頭辞に持つ葉)。']),
    `const TESTID = ${testIds}[KEY];`,
    '',
    ...rowLinkConstLines(plan),
    docComment(['行が 0 件のときの表示(既定の 1 形。部品の `label` から作る)。']),
    plan.label === undefined
      ? `const EMPTY_MESSAGE = ${tsString(TABLE_WORDING.emptyBare())};`
      : `const EMPTY_MESSAGE = \`\${${labels}[KEY]}${TABLE_WORDING.emptySuffix()}\`;`,
    '',
    ...wordingConstLines(plan),
    ...(usesWhen(plan) ? whenLines() : []),
    ...rowInterfaceLines(plan),
    '',
    docComment([`${name} の props(\`R\` は器が渡す行の型 — 生成物が使う欄より多く持っていてよい)。`]),
    `export interface ${name}Props<R extends ${row} = ${row}> {`,
    '  /** 表に出す行(読み取りの結果)。0 件なら空の表示になる。 */',
    '  readonly rows: readonly R[];',
    ...(timeZone ? ['  /** 日時を表示するタイムゾーン(器が `displayTimeZone()` を渡す。生成物は env を読まない)。 */', '  readonly timeZone: string;'] : []),
    '  /** 器が `className` を差し替える口(渡さなければ既定のスタイル)。 */',
    `  readonly skin?: ScreenSkin<${tsString(plan.screen)}> | undefined;`,
    ...rowExtrasPropLines(),
    '}',
    '',
    docComment([
      `読むだけの表(画面 ${plan.screen} の部品 ${plan.component})。`,
      '',
      `仕様: ${screenSpecFile}`,
      '',
      '**この表に業務の判断は 1 つも無い。** 列は仕様の `shows`、見出しは生成の表示名の表、行が 0 件のときの表示も生成物が持つ。',
      '',
      '@param props - 表の props',
      '@param props.rows - 表に出す行',
      ...(timeZone ? ['@param props.timeZone - 日時を表示するタイムゾーン'] : []),
      '@param props.skin - 器が className を差し替える口',
      '@param props.rowExtras - 行ごとに末尾の列へ差し込む手書きの部品(鍵は行の id)',
      '@param props.rowExtraHeader - rowExtras の列の見出し',
      '@returns 表(行が無ければ空の表示)',
    ]),
    `export function ${name}<R extends ${row}>({ rows,${timeZone ? ' timeZone,' : ''} skin, rowExtras, rowExtraHeader }: ${name}Props<R>) {`,
    '  return (',
    '    <div data-testid={TESTID} className={skin?.[KEY] ?? styles.screenTableWrap}>',
    '      {rows.length === 0 ? (',
    `        <p data-testid={\`\${TESTID}.${EMPTY_LEAF}\`} className={styles.screenTableEmpty}>`,
    '          {EMPTY_MESSAGE}',
    '        </p>',
    '      ) : (',
    '        <table className={styles.screenTable}>',
    '          <thead>',
    '            <tr>',
    ...header.flat(),
    ...ROW_EXTRA_HEADER_LINES,
    '            </tr>',
    '          </thead>',
    '          <tbody>',
    '            {rows.map((row) => {',
    ...rowHrefLines(plan),
    '              return (',
    `                <tr key={row.${rowKeyOf(ROW_KEY_FIELD)}} data-testid={\`\${TESTID}.${ROW_LEAF}\`}>`,
    ...plan.columns.flatMap((column) => cellLines(column, column.path === first && linked)),
    rowExtraCellLine('row'),
    '                </tr>',
    '              );',
    '            })}',
    '          </tbody>',
    '        </table>',
    '      )}',
    '    </div>',
    '  );',
    '}',
    '',
  ];
}

/** セル 1 つ(行へのリンクは先頭の列だけ。操作を持つ表の読むだけの列も同じ)。 */
export function cellLines(
  column: ScreenReadPlan['columns'][number],
  linked: boolean,
): readonly string[] {
  const klass = column.kind === 'number' ? 'screenTableCellNumeric' : 'screenTableCell';
  const value = cellExpression(column, 'row');
  const attributes = [...stateAttribute(column, 'row'), `className={styles.${klass}}`].join(' ');
  if (!linked) return [`                  <td ${attributes}>{${value}}</td>`];
  return [
    `                  <td ${attributes}>`,
    '                    <Link data-testid={NAV_TESTID} href={href} className={styles.screenTableLink}>',
    `                      {${value}}`,
    '                    </Link>',
    '                  </td>',
  ];
}
