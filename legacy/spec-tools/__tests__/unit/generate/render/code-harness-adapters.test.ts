/**
 * ハーネスのアダプタ 6 本の生成器(code-harness-adapters。束 ①-d 手 2)のテスト。
 *
 * 固定するのは 3 つである。
 *   1. **6 本が同じ 1 つの宣言の表から出る**こと(置き場は仕組みが決めた 6 パスで、宣言順)。
 *      生成テスト 83 本の import 先を動かさないので、パスの綴りがそのまま契約である。
 *   2. **出力が決定的**であること(同じ入力なら同じ文字列。`generate:check` の鮮度検査の前提)。
 *   3. **throw しないこと** —— 実装の木を持たない製品(`roots.app` が無い)では 0 本を返す。
 *
 * 生成器は純関数で、モデルもガードも読まない(中身は仕組みの形で、アプリの語彙は 1 語も無い)。
 */

import { describe, expect, it } from 'vitest';
import {
  harnessAdapterSections,
  harnessAdaptersGenerator,
} from '../../../../lib/generate/render/code-harness-adapters.js';
import { specModel } from '../../../helpers/model-builder.js';
import { GEN_CTX } from '../../../helpers/generate-context.js';
import { TEST_ROOTS } from '../../../helpers/product-roots.js';
import { FOREIGN_LAYOUT, FOREIGN_ROOTS, TEST_LAYOUT } from '../../../helpers/platform.js';

/** アダプタの置き場(製品の `src/` からの相対。生成テストが import する綴りそのもの)。 */
const ADAPTER_PATHS = [
  'infrastructure/__tests__/rls-world.ts',
  'infrastructure/__tests__/rls-expect.ts',
  'infrastructure/__tests__/eq-world.ts',
  'infrastructure/__tests__/eq-expect.ts',
  'composition/__tests__/eq-save-world.ts',
  'composition/__tests__/eq-save-expect.ts',
] as const;

/** 生成した節を出力先パスの末尾で引く。 */
function sectionOf(files: readonly { readonly file: string; readonly content: string }[], path: string) {
  return files.find((section) => section.file.endsWith(`src/${path}`));
}

describe('code-harness-adapters', () => {
  it('6 本のアダプタが 1 つの宣言の表から、宣言順・丸ごとの生成物として出る', () => {
    const sections = harnessAdaptersGenerator.generate(specModel([]), GEN_CTX);
    expect(sections).toHaveLength(ADAPTER_PATHS.length);
    ADAPTER_PATHS.forEach((path, index) => {
      const section = sections[index];
      expect(section?.file.endsWith(`src/${path}`)).toBe(true);
      expect(section?.wholeFile).toBe(true);
    });
    expect(new Set(sections.map((section) => section.file)).size).toBe(ADAPTER_PATHS.length);
  });

  it('どの本文も、ヘッダ(手編集禁止)と server-only を持ち、ハーネス本体はパッケージから引く', () => {
    for (const section of harnessAdaptersGenerator.generate(specModel([]), GEN_CTX)) {
      expect(section.content).toContain('AUTO-GENERATED by `npm run generate`');
      expect(section.content).toContain("import 'server-only';");
      expect(section.content).toContain('@kaninabe/runtime/testing/');
      expect(section.content.endsWith('\n')).toBe(true);
    }
  });

  it('表明のアダプタは口(harness-ports)を、world のアダプタは対の本体を束ねて渡す', () => {
    const files = harnessAdaptersGenerator.generate(specModel([]), GEN_CTX);
    const rlsExpect = sectionOf(files, 'infrastructure/__tests__/rls-expect.ts');
    const saveExpect = sectionOf(files, 'composition/__tests__/eq-save-expect.ts');
    expect(rlsExpect?.content).toContain('harness-ports');
    expect(saveExpect?.content).toContain('eq-save-world');
  });

  it('出力は決定的である(同じ入力 → 同じ文字列)', () => {
    const first = harnessAdapterSections(TEST_ROOTS, TEST_LAYOUT);
    const second = harnessAdapterSections(TEST_ROOTS, TEST_LAYOUT);
    expect(second).toEqual(first);
    expect(harnessAdaptersGenerator.generate(specModel([]), GEN_CTX)).toEqual(first);
  });

  it('実装の木を持たない製品(roots.app が無い)では throw せず 0 本を返す', () => {
    expect(() => harnessAdapterSections({ ...TEST_ROOTS, app: null }, TEST_LAYOUT)).not.toThrow();
    expect(harnessAdapterSections({ ...TEST_ROOTS, app: null }, TEST_LAYOUT)).toEqual([]);
  });

  it('配置を差し替えると、6 本の置き場がその配置の値になり(基盤の層 4 本・配線の層 2 本)、Next.js の綴りは残らない', () => {
    const files = harnessAdapterSections(FOREIGN_ROOTS, FOREIGN_LAYOUT).map((section) => section.file);
    expect(files).toEqual([
      'app/server_code/checks/glue/rls-world.glue.ts',
      'app/server_code/checks/glue/rls-expect.glue.ts',
      'app/server_code/checks/glue/eq-world.glue.ts',
      'app/server_code/checks/glue/eq-expect.glue.ts',
      'app/server_code/checks/glue_save/eq-save-world.glue.ts',
      'app/server_code/checks/glue_save/eq-save-expect.glue.ts',
    ]);
    expect(files.some((file) => file.includes('__tests__'))).toBe(false);
  });

  it('配置が置き場を決められなければ、黙って 0 本にせず配置の定義の検査を名指して止める', () => {
    expect(() => harnessAdapterSections(TEST_ROOTS, {})).toThrowError(/harness-adapter/);
  });
});
