/**
 * 編集のフォーム・編集する表の行・手書きのフォームが**共有する、競合の表示の部品**(`_screens/generated/form-conflict.tsx`)。
 *
 * 競合とは、refresh で届いた最新が、編集中の欄を他の人が先に変えていた状態(実行時に起きる。判定の正は
 * `@kaninabe/runtime/form-refresh`)。この部品は**知らせと 2 択(最新を取る / 自分の値で上書き)の見た目だけ**を持ち、
 * 判定も解決も持たない(呼び側が `onResolve` で `resolveConflict` へ渡す)。生成の編集表・更新フォームはこれを import し、
 * 手書きのフォームも同じ部品を使う — 文言・葉の名前・見た目が 1 か所にあるので、画面ごとに食い違わない。
 *
 * 文言は仕組みの表(`FORM_WORDING`)から**焼き込む**。アプリの語彙は 1 語も持たない(W1)。
 * 葉の名前(`{testid}.conflict` / `.take_theirs` / `.keep_mine`)は screen-draft.ts の定数が正で、呼び側が `testId` に渡す
 * 接頭辞の下に付く。
 */

import { FORM_WORDING } from '../../messages/messages-screen.js';
import { docComment, tsString } from '../../gen-kit/code-emit.js';
import { CONFLICT_LEAF, KEEP_MINE_LEAF, TAKE_THEIRS_LEAF } from './screen-draft.js';

/** 部品のファイル名(`_screens/generated/` の中)。 */
export const FORM_CONFLICT_FILE = 'form-conflict.tsx';

/** 部品の主 export の名前(期待木の `export`)。 */
export const FORM_CONFLICT_EXPORT = 'FormConflict';

/**
 * 競合の表示の部品(ファイル全体)。入力が無いので常に同じ文字列になる。
 *
 * @returns ファイル全体のソース
 */
export function renderFormConflict(): string {
  return [
    "'use client';",
    '',
    '/**',
    ' * AUTO-GENERATED by `npm run generate` — 手編集禁止。',
    ' *',
    ' * 編集のフォーム・編集する表の行・手書きのフォームが共有する、競合(編集中の欄を他の人が先に変更していた)の',
    ' * 知らせと、解き方の 2 択(最新を取る / 自分の値で上書き)。判定と解決は `@kaninabe/runtime/form-refresh` が持ち、',
    ' * ここは見た目だけを持つ。',
    ' * 変更するときは legacy/spec-tools の screen-form-conflict.ts を編集してから再生成すること。',
    ' */',
    '',
    "import type { ConflictChoice } from '@kaninabe/runtime/form-refresh';",
    "import styles from './default.module.css';",
    '',
    docComment(['競合の知らせの文言。']),
    `const CONFLICT_MESSAGE = ${tsString(FORM_WORDING.conflict())};`,
    '',
    docComment(['競合の解き方 1(手元の編集を捨てて最新の値を取る)のボタンの文言。']),
    `const TAKE_THEIRS_LABEL = ${tsString(FORM_WORDING.take_theirs())};`,
    '',
    docComment(['競合の解き方 2(手元の値を残して、最新の値の上に上書きする)のボタンの文言。']),
    `const KEEP_MINE_LABEL = ${tsString(FORM_WORDING.keep_mine())};`,
    '',
    docComment(['`FormConflict` の props。']),
    `export interface ${FORM_CONFLICT_EXPORT}Props {`,
    '  /** 欄の testid(知らせと 2 択の葉はこれを接頭辞に持つ)。 */',
    '  readonly testId: string;',
    '  /** 送信中か(送信中は 2 択も押せない)。 */',
    '  readonly pending: boolean;',
    '  /** 解き方が選ばれたときに呼ぶ(呼び側が `resolveConflict` へ渡す)。 */',
    '  readonly onResolve: (choice: ConflictChoice) => void;',
    '}',
    '',
    docComment([
      '競合している欄の知らせと、解き方の 2 択(欄のすぐ下に出す)。競合しているときだけ呼び側が描く。',
      '',
      '@param props - 部品の props',
      '@param props.testId - 欄の testid',
      '@param props.pending - 送信中か',
      '@param props.onResolve - 解き方が選ばれたときに呼ぶ',
      '@returns 知らせと 2 択',
    ]),
    `export function ${FORM_CONFLICT_EXPORT}({ testId, pending, onResolve }: ${FORM_CONFLICT_EXPORT}Props) {`,
    '  return (',
    `    <div data-testid={\`\${testId}.${CONFLICT_LEAF}\`} className={styles.screenConflict} aria-live="polite">`,
    '      <span>{CONFLICT_MESSAGE}</span>',
    `      <button data-testid={\`\${testId}.${TAKE_THEIRS_LEAF}\`} type="button" disabled={pending} onClick={() => onResolve('theirs')}>`,
    '        {TAKE_THEIRS_LABEL}',
    '      </button>',
    `      <button data-testid={\`\${testId}.${KEEP_MINE_LEAF}\`} type="button" disabled={pending} onClick={() => onResolve('mine')}>`,
    '        {KEEP_MINE_LABEL}',
    '      </button>',
    '    </div>',
    '  );',
    '}',
    '',
  ].join('\n');
}
