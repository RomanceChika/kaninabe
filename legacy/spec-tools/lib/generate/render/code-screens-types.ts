    '  /** 見出しの葉(表だけ。`column.{欄}`)。 */',
    '  readonly columns?: readonly string[];',
    '  /** 編集してよい欄に入っているときだけ描かれる見出しの葉(編集する表だけが持つ。`column.{欄}`)。 */',
    '  readonly columnsIfWritable?: readonly string[];',
    '  /** 行ごとに必ず描かれる操作の葉(編集する表の保存ボタン。行が 1 件以上あるとき)。 */',
    '  readonly rowActions?: readonly string[];',
    '  /** 行のボタン・ボタン列の葉(遷移はイベントの名前・削除は `delete`)。行の状態と実行者のロールの交差で**出ることがある**もの。 */',
