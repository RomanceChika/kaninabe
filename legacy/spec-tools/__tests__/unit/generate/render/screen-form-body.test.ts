import type { ScreenFormPlan } from '../../../../lib/generate/render/screen-form-plan.js';
import { createGuardServices } from '../../../../lib/guard/services.js';
import { TEST_ROOTS } from '../../../helpers/product-roots.js';
import { TEST_PLATFORM, TEST_LAYOUT, TEST_BODY_MODULES } from '../../../helpers/platform.js';
import { specModel } from '../../../helpers/model-builder.js';
import { screenSpec } from '../../../helpers/screen-builder.js';
import { NO_GATES } from '../../../helpers/generate-context.js';

/** 作成フォームの計画(欄は text / 複数行 / 選択 / チェックボックス)。 */
function createPlan(overrides: Partial<ScreenFormPlan> = {}): ScreenFormPlan {
  return {
    screen: 'sample_admin',
    component: 'sample_form',
    path: 'body.center.sample_form',
    action: 'sample.create',
    shape: 'create',
    entity: 'sample',
    controls: [
      { field: 'name', kind: 'text' },
      { field: 'note', kind: 'multiline' },
      { field: 'level', kind: 'select' },
      { field: 'active', kind: 'checkbox' },
    ],
    supplied: ['owner_id'],
    hasEnumLabels: true,
    confirmRequired: false,
    file: screenFormFile('sample_admin', 'sample_form'),
    exportName: screenFormExport('sample_admin', 'sample_form'),
    ...overrides,
  };
}

/** 本体を 1 つの文字列にする。 */
function source(plan: ScreenFormPlan): string {
  return renderScreenFormBody(plan, 'docs/specs/frontend/screens/admin/sample_admin.md', TEST_BODY_MODULES).join('\n');
}

describe('名前', () => {
  it('ファイル名は {画面}.{部品}.tsx、export は Pascal の連結', () => {
    expect(screenFormFile('sample_admin', 'sample_form')).toBe('sample_admin.sample_form.tsx');
    expect(screenFormExport('sample_admin', 'sample_form')).toBe('SampleAdminSampleForm');
  });
});

describe('作成フォームの本体', () => {
  const text = source(createPlan({ label: '標本を登録する' }));

  it('use client と生成ヘッダと正の仕様を持つ', () => {
    expect(text.startsWith("'use client';")).toBe(true);
    expect(text).toContain('AUTO-GENERATED by `npm run generate`');
    expect(text).toContain('docs/specs/frontend/screens/admin/sample_admin.md');
  });

  it('入力スキーマ・testid の根・skin のキーは部品のキーで引く', () => {
    expect(text).toContain("const SCHEMA = operationInputSchemas['sample.create'];");
    expect(text).toContain("const KEY = 'body.center.sample_form' as const;");
    expect(text).toContain('const TESTID = sampleAdminTestIds[KEY];');
    expect(text).toContain('className={skin?.[KEY] ?? styles.screenForm}');
    expect(text).toContain("readonly skin?: ScreenSkin<'sample_admin'> | undefined;");
  });

  it('欄は宣言の順に FormRow で並び、葉は欄の名前・submit・error', () => {
    const order = ['name', 'note', 'level', 'active'].map((field) => text.indexOf(`\${TESTID}.${field}\``));

    expect(order.every((at) => at > 0)).toBe(true);
    expect([...order].sort((a, b) => a - b)).toEqual(order);
    expect(text).toContain('`${TESTID}.submit`');
    expect(text).toContain('errorTestId={`${TESTID}.error`}');
  });

  it('選択欄は enum の表示名の表を、表示名は {entity}FieldLabels を引く', () => {
    expect(text).toContain("import { sampleFieldLabels, sampleEnumLabels } from '@/domain/generated/sample.labels';");
    expect(text).toContain('optionLabels={sampleEnumLabels.level}');
    expect(text).toContain('label={sampleFieldLabels.name}');
    expect(text).toContain('fieldLabels={sampleFieldLabels}');
  });

  it('参照の欄は入力欄を出さず initial で受ける。選択欄はスキーマの先頭の選択肢が初期値', () => {
    expect(text).toContain("const SUPPLIED = ['owner_id'] as const;");
    expect(text).toContain("'owner_id': initial['owner_id'] ?? ''");
    expect(text).toContain("'level': initial['level'] ?? FORM.fields.level.options?.[0] ?? ''");
    expect(text).not.toContain('${TESTID}.owner_id');
  });

  it('label があれば見出しと送信ボタンの文言になる(送信中は固定文言)', () => {
    expect(text).toContain("import { sampleAdminLabels, sampleAdminTestIds } from '@/domain/generated/testids';");
    expect(text).toContain('const TITLE = sampleAdminLabels[KEY];');
    expect(text).toContain('<h2 className={styles.screenFormTitle}>{TITLE}</h2>');
    expect(text).toContain("{phase === 'pending' ? '送信中…' : TITLE}");
  });

  it('成功したら入力欄を初期値に戻してから onSuccess を呼ぶ', () => {
    expect(text).toContain('setValues(startValues(initial));');
    expect(text).toContain('onSuccess?.();');
  });

  it('送る前の写しは collectRow と生成 zod(サーバーと同じスキーマ)で行う', () => {
    expect(text).toContain('collectRow(FORM, [...SUPPLIED, ...TEXT_FIELDS], FLAG_FIELDS, values)');
    expect(text).toContain('SCHEMA.safeParse(row.value)');
  });

  it('Server Action は import せず props で受ける(no-direct-action-call)', () => {
    expect(text).not.toMatch(/from '[^']*_actions/);
    expect(text).toContain('readonly action: (input: Input) => Promise<ActionResult<unknown>>;');
  });
});

describe('送信の意図の名指し(点検 22 回目 B22-1)', () => {
  it('器が渡す欄(SUPPLIED)があれば、それだけで意図を名指す(利用者が入れる欄は名指さない)', () => {
    const text = source(createPlan());
    expect(text).toContain("const SUPPLIED = ['owner_id'] as const;");
    expect(text).toContain('intentOf={(input) => intentOfFields(input, SUPPLIED)}');
    expect(text).toContain("import { ActionForm, intentOfFields } from '@/components/action-runner';");
    // 欄の全部(TEXT_FIELDS)で名指す形は出さない(選ぶ参照を直した押し直しが新しい鍵になる)。
    expect(text).not.toMatch(/intentOfFields\([^)]*TEXT_FIELDS/u);
  });

  it('器が渡す欄が無ければ intentOf を渡さない(既定 = いつも同じ意図)', () => {
    const text = source(createPlan({ supplied: [] }));
    expect(text).not.toContain('intentOf');
    expect(text).toContain("import { ActionForm } from '@/components/action-runner';");
  });
});

describe('欄ごとの選択肢(choices)', () => {
  const text = source(createPlan());

  it('器が欄ごとの選択肢を渡せる(参照の欄・実行時に決まる値域)', () => {
    expect(text).toContain("import type { FormChoice } from '@/components/form-row';");
    expect(text).toContain('readonly choices?: Readonly<Record<string, readonly FormChoice[]>> | undefined;');
  });

  it('チェックボックス以外の欄は choices を引いて FormRow に渡す(渡されたら選択欄になる)', () => {
    expect(text).toContain("choices={choices?.['name']}");
    expect(text).toContain("choices={choices?.['level']}");
    expect(text).not.toContain("choices={choices?.['active']}");
  });
});

describe('label が無いフォーム', () => {
  const text = source(createPlan({ hasEnumLabels: false, controls: [{ field: 'name', kind: 'text' }] }));

  it('見出しを出さず、送信ボタンは固定文言、欄の表示名は {entity}FieldLabels から引く', () => {
    expect(text).not.toContain('<h2');
    expect(text).not.toContain('const TITLE');
    expect(text).toContain("{phase === 'pending' ? '送信中…' : '送信'}");
    expect(text).toContain('label={sampleFieldLabels.name}');
    expect(text).toContain("import { sampleFieldLabels } from '@/domain/generated/sample.labels';");
    expect(text).toContain("import { sampleAdminTestIds } from '@/domain/generated/testids';");
  });
});

describe('編集フォームの本体', () => {
  const text = source(
    createPlan({
      shape: 'update',
      action: 'sample.update',
      supplied: ['id'],
      controls: [
        { field: 'name', kind: 'text' },
        { field: 'active', kind: 'checkbox' },
      ],
      hasEnumLabels: false,
    }),
  );

  it('変わった欄だけを送る(baseline と違う欄。変更が無い・競合が残っていれば送らない・送信ボタンも押せない)', () => {
    expect(text).toContain('const changed = changedFields(view.draft.baseline, values, EDIT_FIELDS.filter(shown));');
    expect(text).toContain('if (changed.length === 0 || view.conflicts.length > 0) return { ok: false, issues: [] };');
    expect(text).toContain("disabled={phase === 'pending' || changed.length === 0 || view.conflicts.length > 0}");
    // 最新の props との差で決めない(旧い判定。他の人の更新が届くと触っていない欄を再送する)
    expect(text).not.toContain('values[field] !== start[field]');
  });

  it('入力は 2 層(baseline / values)で持ち、最新の props は毎レンダー導出して取り込む(useEffect も最新の state 保持も使わない)', () => {
    expect(text).toContain('const start = startValues(initial);');
    expect(text).toContain('const [draft, setDraft] = useState<FormDraft<string>>(() => ({ baseline: start, values: start }));');
    expect(text).toContain('const view = reconcileFormDraft(draft, start, EDIT_FIELDS);');
    expect(text).toContain('const values = view.draft.values;');
    expect(text).toContain("import { acceptSaved, editField, reconcileFormDraft, resolveConflict } from '@kaninabe/runtime/form-refresh';");
    expect(text).toContain("import { changedFields, formOf, toFieldIssues } from '@kaninabe/runtime/form';");
    expect(text).not.toContain('useEffect');
    expect(text).not.toContain('setValues');
    // 入力は view を土台に積む(取り込んだ最新を捨てない)。その欄の held はここで消費される
    expect(text).toContain('setDraft(editField(view.draft, field, next));');
    expect(text).toContain("onChange={(next) => edit('name', next)}");
  });

  it('競合は共有の部品 FormConflict に任せ(知らせと 2 択の文言・葉・見た目は 1 か所)、欄ごとに出す', () => {
    expect(text).toContain("import { FormConflict } from './form-conflict';");
    expect(text).toContain("{conflictView('name', phase === 'pending')}");
    expect(text).toContain(
      '<FormConflict testId={`${TESTID}.${field}`} pending={pending} onResolve={(choice) => resolveField(field, choice)} />',
    );
    expect(text).toContain("setDraft(resolveConflict(view.draft, start, field, choice));");
    // 文言・葉・クラスはこの生成物に重ねて持たない(共有の部品が正)
    expect(text).not.toContain('CONFLICT_MESSAGE');
    expect(text).not.toContain('screenConflict');
    expect(text).not.toContain('.take_theirs');
  });

  it('編集してよい欄(writable)に入っているものだけを出す', () => {
    expect(text).toContain('readonly writable?: readonly string[] | undefined;');
    expect(text).toContain("{shown('name') ? (");
    expect(text).toContain("{shown('active') ? (");
  });

  it('現在の値は initial から受け、成功しても入力欄を戻さない(編集中の値が正)', () => {
    expect(text).not.toContain('setValues(startValues(initial));');
    // 成功のあとは送った値を保存済みの値として覚える(実行器は onSuccess → refresh の順。自分の保存が競合に見えない)
    expect(text).toContain('onSuccess={(_, sent) => {');
    // 保存した時点の最新(start)を held に覚えさせる(refresh が届くまでの再描画で旧値に戻らない)
    expect(text).toContain('setDraft((current) => acceptSaved(current, sentValues(sent), start));');
    expect(text).toContain('onSuccess?.();');
  });

  it('initial は操作の入力と同じ型で受け、入力欄の文字列への写しは生成物がフォームの口で行う(数値・日時・真偽値の往復)', () => {
    expect(text).toContain('readonly initial?: Readonly<Partial<Input>> | undefined;');
    expect(text).toContain('function startValues(initial: Readonly<Partial<Input>>): Record<string, string> {');
    // 文字列・数値・日時は toInputValue(送信側 parseField の逆向き)で写す。器が文字列にしない。
    expect(text).toContain("'name': FORM.toInputValue('name', initial.name)");
    // 真偽値は入力の真偽値そのものを目盛りに写す(null / 未指定は入っていない)。
    expect(text).toContain("'active': initial.active === true ? CHECKED : ''");
    expect(text).toContain("import { CHECKED, FormRow, collectRow } from '@/components/form-row';");
    // 識別子は文字列のまま受ける。
    expect(text).toContain("'id': initial.id ?? ''");
  });

  it('選択欄の編集は現在の値、無ければ先頭の選択肢', () => {
    const select = source(
      createPlan({ shape: 'update', action: 'sample.update', supplied: ['id'], controls: [{ field: 'level', kind: 'select' }] }),
    );

    expect(select).toContain("'level': FORM.toInputValue('level', initial.level) || FORM.fields.level.options?.[0] || ''");
  });
});

