/**
 * external_spec の受信の行 1 件 → **受信の RPC の migration**(`supabase/migrations/{migration}`)。
 *
 * ADR-0011 §4「保存点の内側は全部か無しか」を受信に当てたものである。受信で起きることは
 * 2 つ —— 外部イベント ID を冪等に**記録**し、写像されたドメインイベントへ**遷移**する ——
 * であり、この 2 つは同じトランザクションに入っていなければならない。
 *
 * **なぜ 1 トランザクションでなければならないか。** 記録だけが成功して遷移が落ちると、相手が
 * 再送しても記録済みの外部イベント ID が「反映済み」と判定されて no-op になり、その通知は
 * **永久に失われる**(入金通知を取りこぼす形)。同じトランザクションなら、遷移が 0 行
 * (状態が合わない)のときに記録も戻る = イベント ID も残らないので、相手の再送でそのまま
 * 再試行される。間に outbox もワーカーも要らない。
 *
 * 生成するのは「既存の RPC を名前付き記法で 2 本呼ぶ plpgsql」であり、複合 RPC
 * (code-usecase-rpc.ts)と同じ形である。どちらの引数に何を渡すかは宣言だけから決まり、
 * 決まらない引数が 1 本でもあれば**生成時エラー**にする(同じ問いを X5 が先に立てている)。
 *
 * 規約どおりファイル I/O はせず、モデルから GeneratedSection を返す純粋関数である。
 */

import { sqlCommentText } from '../../kernel/safe-text.js';
import type { SpecModel } from '../../model/types.js';
import type { DocGenerator, GeneratedSection, GenerateContext } from '../../gen-kit/generator.js';
import type { InboundCall, InboundPlan } from '../../inbound/inbound-plan.js';
import { INBOUND_ARGS, INBOUND_PARAMS, planInbound } from '../../inbound/inbound-plan.js';
import type { InboundIntegrationDecl } from '../../model/external/types.js';
import { isInbound } from '../../model/external/types.js';
import { preconditionFailure } from '../../kernel/generator-precondition.js';
import { raiseRefusal } from '../../sql/refusal-codes.js';
import { sqlString } from './usecase-sql.js';
import { dropStaleOverloads } from '../../sql/rpc-signature.js';
import { migrationPath } from '../../model/product/paths.js';
import type { PlatformProfile } from '../../model/product/platform-profile.js';
import { exposed, privilegedRole } from '../../sql/platform-sql.js';


/** 記録の行を受ける変数名。 */
const RECORD_VAR = 'v_record';

/** 遷移の行を受ける変数名。 */
const TARGET_VAR = 'v_target';

/**
 * 全 external_spec の受信の行から受信の RPC の migration を生成するジェネレーター。
 * 出力は受信 1 本ごとに `supabase/migrations/{migration}`(ファイル全体)。
 */
export const inboundRpcGenerator: DocGenerator = {
  id: 'code-inbound-rpc',

  generate(model: SpecModel, ctx: GenerateContext): GeneratedSection[] {
    const catalog = ctx.external?.catalog;
    if (catalog === undefined || catalog === null) return [];
    if (ctx.dataTables === undefined || !ctx.dataTables.available) return [];
    const sections: GeneratedSection[] = [];
    for (const integration of catalog.integrations.filter(isInbound)) {
      const planned = planInbound(integration, { domain: model, dataTables: ctx.dataTables, roots: ctx.roots });
      // 接地は X5 が先に同じ関数で見ている。破れていたらここは「検査の穴」なので、
      // その検査器の ID を示して Finding の形で止める(scripts-code-quality.md)。
      if (!planned.ok) {
        return preconditionFailure(
          'X5',
          planned.problems.map((problem) => ({
            message: problem.message,
            suggestion: problem.suggestion,
            counterexample: problem.counterexample,
            location: integration.location,
          })),
        );
      }
      sections.push({
        file: migrationPath(ctx.roots, `${integration.migration}`),
        content: renderMigration(planned.plan, catalog.location.file, ctx.platform),
        wholeFile: true,
      });
    }
    return sections;
  },
};

/** migration 1 枚を組み立てる。 */
function renderMigration(plan: InboundPlan, specFile: string, platform: PlatformProfile): string {
  const integration = plan.integration;
  return [
    ...header(plan, specFile),
    '',
    ...dropStaleOverloads(platform.exposedSchema, plan.rpcName, INBOUND_ARGS),
    '',
    `create or replace function ${exposed(platform, plan.rpcName)}(`,
    INBOUND_PARAMS.map((name, index) => `    ${name} ${INBOUND_ARGS[index]}`).join(',\n'),
    ') returns jsonb',
    'language plpgsql',
    'security definer',
    'set search_path = public',
    'as $$',
    'declare',
    `    ${RECORD_VAR} public.${plan.record.table};`,
    `    ${TARGET_VAR} public.${plan.transition.table};`,
    'begin',
    ...recordBlock(plan, platform),
    '',
    ...transitionBlock(plan, platform),
    '',
    "    return jsonb_build_object('status', 'applied');",
    'end;',
    '$$;',
    '',
    ...grants(plan, integration, platform),
    '',
  ].join('\n');
}

/** 先頭の AUTO-GENERATED ヘッダ(SQL コメント)。 */
function header(plan: InboundPlan, specFile: string): string[] {
  const integration = plan.integration;
  return [
    '-- AUTO-GENERATED by `npm run generate` — 手編集禁止。',
    '--',
    '-- このファイルの正は次の仕様であり、ここはその機械的な写像にすぎない。',
    '-- 変更するときは仕様を編集してから再生成すること(ADR-0006)。',
    `--   - ${sqlCommentText(specFile)}(受信 ${integration.id})`,
    '--',
    '-- SQL が変わる仕様変更をしたら migration の名前を新しくする(適用済みの migration は',
    '-- 書き換えない。migrations.md §生成 migration)。関数は create or replace なので、新しい',
    '-- ファイルが同じ名前の関数を置き換える。',
    '--',
    `-- 目的: ${sqlCommentText(integration.summary)}`,
    `-- 記録: ${plan.record.table}.${plan.eventIdColumn}(外部イベント ID の一意制約 = 冪等の実体)`,
    `-- 遷移: ${integration.emits}(${plan.expectedState} → ${plan.nextState})`,
  ];
}

/**
 * ① 記録。
 *
 * 外部イベント ID の一意制約に当たったら、遷移を 1 つも起こさずに `duplicate` で閉じる
 * (相手の再送は正常な動作であり、2 度反映しない)。副ブロックの例外処理はその一意制約だけを
 * 冪等の合図として読む —— ここで捕まえずに外へ投げると、再送のたびに 5xx を返し続けることになる。
 */
function recordBlock(plan: InboundPlan, platform: PlatformProfile): string[] {
  return [
    '    -- ① 記録(冪等の鍵): 同じ外部イベント ID の再送はここで一意制約に当たり、',
    '    --    遷移を 1 つも起こさずに duplicate で閉じる。',
    '    begin',
    ...callStatement(plan.record, RECORD_VAR, '        ', platform),
    '    exception',
    '        when unique_violation then',
    "            return jsonb_build_object('status', 'duplicate');",
    '    end;',
  ];
}

/**
 * ② 遷移。
 *
 * ①と同じトランザクションで実行する。0 行(宣言された `from` と実際の状態が食い違う)は例外で
 * 全体を戻す —— 記録も残らないので、相手の再送でそのまま再試行される。合図の綴りは定型 RPC の
 * 競合とまったく同じ(`UC409` + `usecase_conflict:{操作}`)であり、app 側の写像を 1 つに保つ。
 */
function transitionBlock(plan: InboundPlan, platform: PlatformProfile): string[] {
  const emits = plan.integration.emits;
  return [
    '    -- ② 遷移(①と同じトランザクション): 状態が合わなければ例外で全体を戻す。',
    `    --    記録も残らないので、相手の再送でそのまま再試行される(${plan.expectedState} → ${plan.nextState})。`,
    ...callStatement(plan.transition, TARGET_VAR, '    ', platform),
    '    if not found then',
    raiseRefusal('conflict', emits, '        '),
    '    end if;',
  ];
}

/** RPC 1 本の呼び出し(名前付き記法)。 */
function callStatement(call: InboundCall, target: string, indent: string, platform: PlatformProfile): string[] {
  return [
    `${indent}select * into ${target} from ${exposed(platform, call.fn.name)}(`,
    call.args.map((arg) => `${indent}    ${arg.name} => ${arg.expression}`).join(',\n'),
    `${indent});`,
  ];
}

/** 実行権限(RPC は内部実行のロールからしか呼び出させない。database-guards.md)。 */
function grants(plan: InboundPlan, integration: InboundIntegrationDecl, platform: PlatformProfile): string[] {
  const signature = `${exposed(platform, plan.rpcName)}(${INBOUND_ARGS.join(', ')})`;
  return [
    `comment on function ${signature} is`,
    `    ${sqlString(`${integration.summary} — 受信の記録と遷移を 1 トランザクションで実行する(生成物)。`)};`,
    '',
    `revoke all on function ${signature} from public;`,
    `grant execute on function ${signature} to ${privilegedRole(platform)};`,
  ];
}
