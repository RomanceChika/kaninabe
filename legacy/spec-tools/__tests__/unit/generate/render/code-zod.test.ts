import { describe, expect, it } from 'vitest';

import { zodSchemaGenerator } from '../../../../lib/generate/render/code-zod.js';
import type { FieldDef } from '../../../../lib/model/types.js';
import { aggregate, entitySpec, field, machine, specModel } from '../../../helpers/model-builder.js';
import { GEN_CTX } from '../../../helpers/generate-context.js';
import { tsString } from '../../../../lib/gen-kit/code-emit.js';
import { urlRegexSource } from '../../../../lib/kernel/url-format.js';

/** field() ヘルパーは制約(max_length 等)を持たないため、必要な分だけ後付けする。 */
function withConstraints(base: FieldDef, extra: Partial<FieldDef>): FieldDef {
  return { ...base, ...extra };
}

/** 1 集約だけのモデルを生成し、その 1 セクションを返す。 */
function generateOne(fields: readonly FieldDef[], name = 'entry'): { file: string; content: string } {
  const model = specModel([
    aggregate(name, { entity: entitySpec(name, { fields }) }),
    aggregate('entry_machine_holder', {
      stateMachines: [machine('entry', { states: ['draft', 'submitted', 'accepted'], initial: 'draft' })],
    }),
  ]);
  const sections = zodSchemaGenerator.generate(model, GEN_CTX);
  const section = sections[0];
  if (section === undefined) throw new Error('セクションが生成されませんでした');
  return { file: section.file, content: section.content };
}

describe('zodSchemaGenerator', () => {
  it('ファイル全体モードで app/src/domain/generated/{aggregate}.schema.ts を出力する', () => {
    const model = specModel([
      aggregate('entry', { entity: entitySpec('entry', { fields: [field('id', { kind: 'uuid' })] }) }),
      aggregate('program', { entity: entitySpec('program_item', { fields: [] }) }),
      aggregate('no_entity', {}),
    ]);

    const sections = zodSchemaGenerator.generate(model, GEN_CTX);

    expect(sections).toHaveLength(2);
    expect(sections[0]?.file).toBe('app/src/domain/generated/entry.schema.ts');
    expect(sections[0]?.wholeFile).toBe(true);
    expect(sections[0]?.marker).toBeUndefined();
    // ファイル名は集約名、スキーマ名はエンティティ名(camelCase)から作る
    expect(sections[1]?.file).toBe('app/src/domain/generated/program.schema.ts');
    expect(sections[1]?.content).toContain('export const programItemRowSchema = z.strictObject({});');
    expect(sections[1]?.content).toContain('export type ProgramItemRow = z.infer<typeof programItemRowSchema>;');
  });

  it('AUTO-GENERATED ヘッダと仕様ファイルのパス、zod の import を先頭に置く', () => {
    const { content } = generateOne([field('id', { kind: 'uuid' })]);

    expect(content.startsWith('/**\n * AUTO-GENERATED by `npm run generate` — 手編集禁止。')).toBe(true);
    expect(content).toContain(' *   - docs/specs/domain/entry/entity.md');
    expect(content).toContain("import { z } from 'zod';");
    expect(content).toContain('仕様: docs/specs/domain/entry/entity.md');
  });

  it('各フィールド型を zod v4 の式に写像する', () => {
    const { content } = generateOne([
      field('id', { kind: 'uuid' }, { required: true }),
      field('workshop_id', { kind: 'ref', entity: 'workshop' }, { required: true }),
      field('title', { kind: 'string' }, { required: true }),
      field('note', { kind: 'text' }, { required: true }),
      field('count', { kind: 'integer' }, { required: true }),
      field('ratio', { kind: 'decimal' }, { required: true }),
      field('agreed', { kind: 'boolean' }, { required: true }),
      field('birthday', { kind: 'date' }, { required: true }),
      field('starts_at', { kind: 'datetime' }, { required: true }),
      field('gender', { kind: 'enum', values: ['male', 'female'] }, { required: true }),
    ]);

    expect(content).toContain('  id: z.uuid(),');
    expect(content).toContain('  workshop_id: z.uuid(),');
    expect(content).toContain('  title: textInput().trim().min(1),');
    expect(content).toContain('  note: textInput().trim().min(1),');
    expect(content).toContain('  count: z.number().int(),');
    expect(content).toContain('  ratio: z.number(),');
    expect(content).toContain('  agreed: z.boolean(),');
    expect(content).toContain('  birthday: z.iso.date(),');
    expect(content).toContain('  starts_at: z.iso.datetime({ offset: true }),');
    expect(content).toContain("  gender: z.enum(['male', 'female']),");
  });

  it('format: url は URL の綴りを .regex() に写す(max_length の後ろ。pattern と同じ位置・同じ書き方)', () => {
    const { content } = generateOne([
      withConstraints(field('ticket_url', { kind: 'string' }), { format: 'url', maxLength: 500 }),
    ]);

    expect(content).toContain(`ticket_url: textInput().max(500).regex(new RegExp(${tsString(urlRegexSource('http_https'))})).nullable()`);
  });

  it('format: url の欄の綴りは pattern の欄と同じ位置で、数の欄・text 以外の型には効かない', () => {
    const { content } = generateOne([withConstraints(field('n', { kind: 'integer' }), { format: 'url' })]);

    expect(content).not.toContain('.regex(');
  });

  it('max_length / min / max / pattern を制約メソッドに写像する', () => {
    const { content } = generateOne([
      withConstraints(field('title', { kind: 'string' }, { required: true }), { maxLength: 100 }),
      withConstraints(field('duration_min', { kind: 'integer' }, { required: true }), { min: 1, max: 60 }),
      withConstraints(field('code', { kind: 'string' }, { required: true }), { pattern: '^[A-Z]+$' }),
    ]);

    expect(content).toContain('  title: textInput().trim().min(1).max(100),');
    expect(content).toContain('  duration_min: z.number().int().min(1).max(60),');
    expect(content).toContain("  code: textInput().trim().min(1).regex(new RegExp('^[A-Z]+$')),");
  });

  it('required の文字列は「空白を除いて 1 文字以上」に写す(trim が先)', () => {
    const { content } = generateOne([
      field('title', { kind: 'string' }, { required: true }),
      field('note', { kind: 'text' }, { required: true }),
      // required でない文字列は空文字を許す(未入力との区別はフォーム側の変換規則が持つ)
      field('composer', { kind: 'string' }),
      // 文字列以外には効かない
      field('duration_min', { kind: 'integer' }, { required: true }),
    ]);

    expect(content).toContain('  title: textInput().trim().min(1),');
    expect(content).toContain('  note: textInput().trim().min(1),');
    // trim / min(1) が付くのは required の文字列だけ(任意の文字列は空文字も許す)
    expect(content).toContain('  composer: textInput().optional(),');
    expect(content).toContain('  duration_min: z.number().int(),');
  });

  // 点検 18 回目 O18-2: 利用者が入力する文字列は、欄ごとに書き足さず、生成器が 1 か所で共通の起点から始める。
  // 更新の入力スキーマは行のスキーマから pick で借りるので、行にも同じ起点が要る(行だけ素の z.string() だと更新が NUL を通す)。
  it('文字列(string / text)は行にも入力にも textInput() から始まり、文字列でない欄・state 型は変わらない', () => {
    const { content } = generateOne([
      field('id', { kind: 'uuid' }, { required: true }),
      field('title', { kind: 'string' }, { required: true }),
      field('note', { kind: 'text' }),
      field('count', { kind: 'integer' }, { required: true }),
      field('state', { kind: 'state', machine: 'entry' }),
    ]);
    const [rowPart = '', inputPart] = content.split('export const entryInputSchema');

    expect(content).toContain("import { textInput } from '@kaninabe/runtime/text-input';");
    expect(rowPart).toContain('  title: textInput().trim().min(1),');
    expect(rowPart).toContain('  note: textInput().nullable(),');
    expect(rowPart).toContain('  count: z.number().int(),');
    expect(rowPart).toContain("  state: z.enum(['draft', 'submitted', 'accepted']),");
    expect(inputPart).toContain('  title: textInput().trim().min(1),');
    expect(inputPart).toContain('  note: textInput().optional(),');
    expect(inputPart).toContain('  count: z.number().int(),');
    // 文字列の欄は 1 つも素の z.string() で出ない
    expect(content).not.toContain('z.string()');
  });

  it('文字列の欄が 1 つも無い集約には textInput の import を出さない(未使用の import を作らない)', () => {
    const { content } = generateOne([field('id', { kind: 'uuid' }, { auto: true }), field('count', { kind: 'integer' }, { required: true })]);

    expect(content).not.toContain('text-input');
    expect(content).not.toContain('textInput');
  });

  it('state 型はその状態機械の states から z.enum を生成する(モデル横断参照)', () => {
    const { content } = generateOne([field('state', { kind: 'state', machine: 'entry' }, { required: true })]);

    expect(content).toContain("  state: z.enum(['draft', 'submitted', 'accepted']),");
  });

  it('参照先の状態機械が無ければ z.string() に縮退する(verify 通過後には起きない)', () => {
    const model = specModel([
      aggregate('entry', {
        entity: entitySpec('entry', {
          fields: [field('state', { kind: 'state', machine: 'missing' }, { required: true })],
        }),
      }),
    ]);

    const content = zodSchemaGenerator.generate(model, GEN_CTX)[0]?.content ?? '';

    expect(content).toContain('  state: z.string(),');
  });

  it('required でないフィールドは row では .nullable()、input では .optional() になる', () => {
    // 「値が無い」の形はスキーマによって違う — 行は全列を持つので null、入力はキーごと無い(FD/FB)
    const { content } = generateOne([
      field('title', { kind: 'string' }, { required: true }),
      withConstraints(field('composer', { kind: 'string' }), { maxLength: 100 }),
    ]);
    const [rowPart, inputPart] = content.split('export const entryInputSchema');

    expect(rowPart).toContain('  title: textInput().trim().min(1),');
    expect(rowPart).toContain('  composer: textInput().max(100).nullable(),');
    // 文字列は共通の起点(制御文字を拒む textInput)から始まる(行にも入力にも)
    expect(inputPart).toContain('  composer: textInput().max(100).optional(),');
  });

  it('Input スキーマは auto:true と state 型フィールドを除外する', () => {
    const { content } = generateOne([
      field('id', { kind: 'uuid' }, { auto: true }),
      field('title', { kind: 'string' }, { required: true }),
      field('composer', { kind: 'string' }),
      field('state', { kind: 'state', machine: 'entry' }),
    ]);

    const [rowPart, inputPart] = content.split('export const entryInputSchema');
    // auto は「入力に現れない」であって「無いことがある」ではない(row では必須)
    expect(rowPart).toContain('  id: z.uuid(),');
    // state も row では必須(初期値は state_spec の initial が決め、列の DEFAULT がその写像)
    expect(rowPart).toContain("  state: z.enum(['draft', 'submitted', 'accepted']),");

    expect(inputPart).toBeDefined();
    expect(inputPart).toContain('  title: textInput().trim().min(1),');
    expect(inputPart).toContain('  composer: textInput().optional(),');
    expect(inputPart).not.toContain('  id:');
    expect(inputPart).not.toContain('  state:');
    expect(content).toContain('export type EntryInput = z.infer<typeof entryInputSchema>;');
  });

  it('row スキーマは閉世界(strictObject)、input スキーマは開世界(object)で出す', () => {
    // 行スキーマが未宣言の列を黙って剥がすと、「DB にあって仕様に無い列」に誰も気づかない。
    // strictObject にすることで row-parity(実 DB の行との突合)が余分な列で失敗する。
    const { content } = generateOne([field('title', { kind: 'string' }, { required: true })]);

    expect(content).toContain('export const entryRowSchema = z.strictObject({');
    expect(content).toContain('export const entryInputSchema = z.object({');
  });

  it('同じモデルからは同じ出力になる(生成物の決定性 — ADR-0006)', () => {
    const fields = [field('id', { kind: 'uuid' }, { auto: true }), field('title', { kind: 'string' }, { required: true })];

    expect(generateOne(fields).content).toBe(generateOne(fields).content);
  });
});
