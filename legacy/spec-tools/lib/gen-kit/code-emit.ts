/**
 * 実装側コード生成(生成物の総置き場)で共有する、ソース文字列の組み立て部品。
 *
 * 生成物はリポジトリにコミットされ CI の鮮度チェックで比較される(ADR-0006)ため、
 * 出力は入力から一意に定まらなければならない。整形の揺れ(改行位置・引用符)を
 * 呼び出し側に委ねず、ここに固定する。
 */

import type { LiteralValue } from '../kernel/literal-value.js';
import { blockCommentText, tsStringLiteral } from '../kernel/safe-text.js';
import { generatedPath } from '../model/product/paths.js';
import type { ProductRoots } from '../model/product/types.js';

/**
 * 実装側生成物の出力先(リポジトリルート相対)。ADR-0006 / ARCH-SP-0002。
 *
 * **置き場そのものは製品が宣言する**(`product.md` の `roots.generated`)。生成器が綴りを
 * 持たないのは、2 つ目の製品が別の配置・別のスタックでも同じ生成器で動くためである(W3)。
 *
 * @param roots 製品が宣言した根
 * @param name 置き場の中のファイル名(省略すると置き場そのもの)
 * @returns リポジトリルート相対のパス
 */
export function generatedFile(roots: ProductRoots, name?: string): string {
  return name === undefined ? generatedPath(roots) : generatedPath(roots, name);
}

/**
 * 生成ファイル先頭に置くヘッダコメント。手編集の禁止と「正はどの仕様か」を示す。
 * @param specFiles この生成物の正となる仕様ファイル(リポジトリルート相対)
 * @returns 末尾に改行を含まない JSDoc ブロック
 */
export function generatedHeader(specFiles: readonly string[]): string {
  return [
    '/**',
    ' * AUTO-GENERATED by `npm run generate` — 手編集禁止。',
    ' *',
    ' * このファイルの正は次の仕様であり、ここはその機械的な写像にすぎない。',
    ' * 変更するときは仕様を編集してから再生成すること(ADR-0006)。',
    // 仕様ファイルのパスはファイルシステムの名前で、改行や `*/` を含みうる(コメントを破らせない)。
    ...specFiles.map((file) => ` *   - ${blockCommentText(file)}`),
    ' */',
  ].join('\n');
}

/**
 * JSDoc ブロックを組み立てる。本文が 1 行なら 1 行形式の JSDoc にする。
 * 空行は ` *` だけの行にする(行末の空白を生成物に残さないため)。
 * **本文は無害化する**(仕様の文字列がここに入る): 要素の中の改行は行を分け、閉じ記号 `*\/` は `*\\/` にする —— コメントの外へ出させない。
 * 正常な本文(改行も閉じ記号も含まない)は 1 バイトも変わらない。
 * @param lines コメント本文の各行(先頭の `*` は不要)
 */
export function docComment(lines: readonly string[]): string {
  const safe = lines.flatMap((line) => line.split(/\r\n|[\n\r\u2028\u2029]/).map((part) => blockCommentText(part)));
  const only = safe.length === 1 ? safe[0] : undefined;
  if (only !== undefined) return `/** ${only} */`;
  const body = safe.map((line) => (line.length === 0 ? ' *' : ` * ${line}`));
  return ['/**', ...body, ' */'].join('\n');
}

/** snake_case の仕様上の識別子を PascalCase の TS 型名にする(例: program_item → ProgramItem)。 */
export function toPascalCase(name: string): string {
  return name
    .split('_')
    .filter((part) => part.length > 0)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

/** snake_case の仕様上の識別子を camelCase の TS 変数名にする(例: program_item → programItem)。 */
export function toCamelCase(name: string): string {
  const pascal = toPascalCase(name);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

/** 文字列を TypeScript のシングルクォート文字列リテラルにする(エスケープ込み。単独の復帰・行の区切り・制御文字も逃がす: `kernel/safe-text.ts`)。 */
export function tsString(value: string): string {
  return tsStringLiteral(value);
}

/** TS のリテラル式として出力できる値(型の正は kernel 層 `literal-value.ts`。ここは型だけを再輸出する)。 */
export type { LiteralValue };

/** ネストの 1 段あたりのインデント。 */
const PAD = '  ';

/** 単一行に収める配列の目安の最大幅。超えたら 1 要素 1 行に折る。 */
const INLINE_WIDTH = 96;

/**
 * 型つきのデータを、そのままリテラル式にできる形かを型で見る写像(`T` がリテラルにできるなら `T`
 * と同じ形、できない(関数・`undefined` の値など)なら `never`)。
 *
 * `LiteralValue` はオブジェクトを `{ [key: string]: LiteralValue }` で持つため、**`interface`
 * で宣言したエンジンの型(`MachineTable` など)は代入できない**(`interface` には暗黙の索引
 * 署名が無い)。そのため生成するデータを `LiteralValue` に潰して `as unknown as` で型を戻す
 * 形になっていた。**データは型つきのまま運び、文字列にする直前(`renderLiteral`)だけが
 * この写像で「リテラルにできる形か」を検査する**。欄が任意(`x?:`)の型は、欄が無ければ
 * 出力にも鍵が出ない。
 */
export type Literalizable<T> = T extends string | number | boolean | null
  ? T
  : T extends (...args: never[]) => unknown
    ? never
    : T extends readonly (infer Item)[]
      ? readonly Literalizable<Item>[]
      : T extends object
        ? { readonly [Key in keyof T]: Literalizable<T[Key]> }
        : never;

/**
 * 値を TypeScript のリテラル式に整形する。オブジェクトのキー順は挿入順を保つ
 * (= 仕様の並び順が出力の並び順になり、決定的)。
 *
 * 引数は `LiteralValue` に限らず、**`Literalizable` を満たす型つきのデータ**(エンジンの
 * `MachineTable` など)をそのまま渡せる。型を `LiteralValue` に潰して戻す必要は無い。
 * @param value 出力する値
 * @param indent 現在のネストの深さ(呼び出し側は 0)
 */
export function renderLiteral<T>(value: T & Literalizable<T>, indent = 0): string {
  return renderAny(value, indent);
}

/** 実体。型の検査は `renderLiteral` の入口で済んでいるので、ここは形だけを見て写す。 */
function renderAny(value: unknown, indent: number): string {
  if (value === null) return 'null';
  if (typeof value === 'string') return tsString(value);
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) return renderArray(value as readonly unknown[], indent);
  return renderObject(value as { readonly [key: string]: unknown }, indent);
}

/** 配列リテラル。要素がすべてスカラーで短ければ 1 行、そうでなければ 1 要素 1 行。 */
function renderArray(items: readonly unknown[], indent: number): string {
  if (items.length === 0) return '[]';
  if (items.every((item) => typeof item !== 'object')) {
    const inline = `[${items.map((item) => renderAny(item, 0)).join(', ')}]`;
    if (inline.length + indent * PAD.length <= INLINE_WIDTH) return inline;
  }
  const inner = PAD.repeat(indent + 1);
  return [
    '[',
    ...items.map((item) => `${inner}${renderAny(item, indent + 1)},`),
    `${PAD.repeat(indent)}]`,
  ].join('\n');
}

/** 識別子としてそのまま書けるキーの形。 */
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/**
 * オブジェクトのキーを出力する形にする。
 *
 * 識別子として妥当ならそのまま、そうでなければ文字列リテラルにする。仕様由来のキーには
 * ドットを含むもの(`{machine}.{event}`)があり、裸で出すと生成物が構文エラーになる。
 */
function renderKey(key: string): string {
  return IDENTIFIER.test(key) ? key : tsString(key);
}

/** オブジェクトリテラル。常に 1 プロパティ 1 行(差分を行単位で読めるようにするため)。 */
function renderObject(object: { readonly [key: string]: unknown }, indent: number): string {
  const entries = Object.entries(object).filter(([, value]) => value !== undefined);
  if (entries.length === 0) return '{}';
  const inner = PAD.repeat(indent + 1);
  return [
    '{',
    ...entries.map(([key, value]) => `${inner}${renderKey(key)}: ${renderAny(value, indent + 1)},`),
    `${PAD.repeat(indent)}}`,
  ].join('\n');
}

/** 生成した定数を深く凍結する補助の関数の名前(`DEEP_FREEZE_HELPER` が定義する)。 */
export const DEEP_FREEZE = 'deepFreeze';

/**
 * 生成した定数を深く凍結する補助の関数の定義(生成物のファイルの中に置く行)。生成した定数は型の上では readonly でも実体は書き換えられ、
 * 任意のモジュールの最上位の `Object.assign` で以後の要求の全部に効く(点検 7 回目 B7-5)ので、値ごと `Object.freeze` で深く凍らせる。
 * 型は引数のまま返す(`as const` の字句の型を保つ)。
 */
export const DEEP_FREEZE_HELPER: readonly string[] = [
  '/** 値を深く凍結する(生成した定数を実行時に書き換えさせない)。型は引数のまま返す。 */',
  `function ${DEEP_FREEZE}<T>(value: T): T {`,
  "  if (typeof value !== 'object' || value === null) return value;",
  `  for (const child of Object.values(value)) ${DEEP_FREEZE}(child);`,
  '  return Object.freeze(value);',
  '}',
];
