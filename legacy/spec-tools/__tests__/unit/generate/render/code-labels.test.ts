/**
 * 表示名テーブル(app/src/domain/generated/{machine}.labels.ts)の生成器のテスト。
 *
 * 対象の要求: 「state_spec の states[].label / events[].label を実装側の定数として出す。
 * label を宣言していないものはキーを持たない」。
 */

import { describe, expect, it } from 'vitest';
import { stateLabelGenerator } from '../../../../lib/generate/render/code-labels.js';
import { accessSpec, aggregate, entitySpec, event, field, machine, specModel } from '../../../helpers/model-builder.js';
import { GEN_CTX } from '../../../helpers/generate-context.js';

/** 1 状態機械だけのモデルを生成し、その本文を返す。 */
function generateOne(spec: ReturnType<typeof machine>): string {
  const model = specModel([aggregate(spec.machine, { stateMachines: [spec] })]);
  const section = stateLabelGenerator.generate(model, GEN_CTX)[0];
  if (section === undefined) throw new Error('セクションが生成されませんでした');
  return section.content;
}

/** 状態とイベントに label を持つ entry 機械。 */
function labelled() {
  return machine('entry', {
    states: ['draft', 'submitted'],
    stateLabels: { draft: '下書き', submitted: '提出済み' },
    initial: 'draft',
    events: [event('submit', { from: ['draft'], to: 'submitted', label: '提出する' })],
  });
}

describe('stateLabelGenerator', () => {
  it('ファイル全体モードで app/src/domain/generated/{machine}.labels.ts を出力する', () => {
    const model = specModel([
      aggregate('entry', {
        stateMachines: [machine('entry', { states: ['draft'], initial: 'draft' })],
      }),
      aggregate('workshop', {
        stateMachines: [machine('workshop', { states: ['draft'], initial: 'draft' })],
      }),
    ]);

    const sections = stateLabelGenerator.generate(model, GEN_CTX);

    // 名前順に出す（状態機械と集約を同じファイル名の空間で束ねるため、宣言順ではない）。
    expect(sections.map((section) => section.file)).toEqual([
      'app/src/domain/generated/entry.labels.ts',
      'app/src/domain/generated/workshop.labels.ts',
    ]);
    expect(sections[0]?.wholeFile).toBe(true);
    expect(sections[0]?.marker).toBeUndefined();
  });

  it('AUTO-GENERATED ヘッダと仕様への参照を出す', () => {
    const content = generateOne(labelled());

    expect(content.startsWith('/**\n * AUTO-GENERATED by `npm run generate` — 手編集禁止。')).toBe(
      true,
    );
    expect(content).toContain(' *   - docs/specs/domain/entry/states.md');
  });

  it('状態の表示名を宣言順の as const オブジェクトにする', () => {
    const content = generateOne(labelled());

    expect(content).toContain('export const entryStateLabels = {');
    expect(content).toContain("  draft: '下書き',");
    expect(content).toContain("  submitted: '提出済み',");
    expect(content).toContain('} as const;');
  });

  it('イベントの表示名も別の定数として出す', () => {
    expect(generateOne(labelled())).toContain(
      "export const entryEventLabels = {\n  submit: '提出する',\n} as const;",
    );
  });

  it('label を宣言していない状態・イベントはキーを持たない', () => {
    const content = generateOne(
      machine('entry', {
        states: ['draft', 'submitted'],
        stateLabels: { draft: '下書き' },
        initial: 'draft',
        events: [event('submit', { from: ['draft'], to: 'submitted' })],
      }),
    );

    expect(content).toContain("export const entryStateLabels = {\n  draft: '下書き',\n} as const;");
    expect(content).toContain('export const entryEventLabels = {} as const;');
  });

  it('同じモデルからは同じ出力になる(生成物の決定性 — ADR-0006)', () => {
    expect(generateOne(labelled())).toBe(generateOne(labelled()));
  });

  it('entity_spec を持つ全エンティティにフィールドの表示名(FieldLabels)を出す。label の無いフィールドはキーを持たない', () => {
    const model = specModel([
      aggregate('entry', {
        entity: entitySpec('entry', {
          fields: [field('title', { kind: 'string' }, { label: '演目名' }), field('note', { kind: 'text' })],
        }),
      }),
    ]);

    const section = stateLabelGenerator.generate(model, GEN_CTX)[0];

    expect(section?.file).toBe('app/src/domain/generated/entry.labels.ts');
    expect(section?.content).toContain('export const entryFieldLabels = {');
    expect(section?.content).toContain("title: '演目名',");
    expect(section?.content).not.toContain('note:');
    // 表示名の源(entity.md)もヘッダの参照に載る。enum の表示名が無いので EnumLabels は出ない。
    expect(section?.content).toContain('docs/specs/domain/entry/entity.md');
    expect(section?.content).not.toContain('EnumLabels');
  });

  it('書き込み規則(writes)を持たない集約にも FieldLabels を出す', () => {
    const model = specModel([
      aggregate('invitation', {
        entity: entitySpec('invitation', { fields: [field('token', { kind: 'string' }, { label: '招待コード' })] }),
        access: accessSpec('invitation', {}),
      }),
    ]);

    const content = stateLabelGenerator.generate(model, GEN_CTX)[0]?.content ?? '';

    expect(content).toContain("export const invitationFieldLabels = {\n  token: '招待コード',\n} as const;");
  });

  it('状態機械と同じ名前の集約は 1 つのファイルに状態・欄・enum の表示名が並ぶ', () => {
    const model = specModel([
      aggregate('entry', {
        stateMachines: [labelled()],
        entity: entitySpec('entry', {
          fields: [{ ...field('kind', { kind: 'enum', values: ['solo'] }, { label: '種別' }), labels: { solo: '独奏' } }],
        }),
      }),
    ]);

    const sections = stateLabelGenerator.generate(model, GEN_CTX);

    expect(sections).toHaveLength(1);
    const content = sections[0]?.content ?? '';
    expect(content).toContain('entryStateLabels');
    expect(content).toContain('entryFieldLabels');
    expect(content).toContain('entryEnumLabels');
  });
});
