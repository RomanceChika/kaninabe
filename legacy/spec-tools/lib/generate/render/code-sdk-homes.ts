/**
 * **外部の SDK の置き場の表**(`app/src/domain/generated/sdk-homes.json`)の生成器(点検 9 回目 B9-4)。
 *
 * 外部の SDK のパッケージは、宣言した置き場の下でだけ値として import できる。置き場は 3 種類ある ——
 *   - 外部連携の `adapter_root`(external_spec の `vocabulary.service[].sdk_packages`)
 *   - 土台(置き場の配置の `sdkPackages`。接続層のクライアントの SDK)
 *   - SDK の UI 部品を引くクライアントの部品(external_spec の `client_ui`。名指したファイルと、そのファイルが引いてよい包みだけ)
 *
 * あわせて**外へ送る口の置き場**(`outbound`。点検 10 回目 B10-3)を出す —— 閉じた表の口(`outbound-primitives.ts` の 1 か所)と、それを値で
 * 引いてよい置き場(全部の外部連携の `adapter_root` と土台)。ESLint の `layer/outbound-primitive-home` と `layer/no-external-network` の
 * 免除の住所がここから読む。
 *
 * 同じ表を検証器の X1 の (d)(製品の木の全部の import を走査する閉世界)が仕様から直に読み、ESLint の層の境界
 * (`@kaninabe/lint-config/policies` の `sdkHomeBoundaries`)がこの JSON から読む。ESLint の設定は Node が直に実行する `.mjs` で
 * TypeScript を経由できないので JSON にする(`lint-exceptions.json` / `framework-structure.json` と同じ理由)。
 * パスは製品の木の根(`app/`)からの相対(ESLint の設定がそこを根に読む)。
 *
 * 純関数(ファイル I/O をしない)。**アプリの語彙は 1 語も持たない**(service の語は仕様の値)。
 */

import type { SpecModel } from '../../model/types.js';
import type { DocGenerator, GeneratedSection, GenerateContext } from '../../gen-kit/generator.js';
import { generatedFile } from '../../gen-kit/code-emit.js';
import { productSdkHomes } from '../../model/framework-base-dirs.js';
import type { ExternalCatalogSpec } from '../../model/external/types.js';
import { OUTBOUND_PRIMITIVE_MODULES } from '../../model/external/outbound-primitives.js';

/** 置き場 1 つ(ディレクトリ)。 */
export interface SdkHomeRow {
  /** 誰の置き場か(`service:{語}` か `base:{土台の説明}`)。 */
  readonly owner: string;
  /** 置き場(製品の木の根からの相対)。 */
  readonly dir: string;
  /** この置き場の下でだけ引ける包みの綴り。 */
  readonly packages: readonly string[];
}

/** SDK の UI 部品を引くクライアントの部品 1 つ。 */
export interface SdkClientUiRow {
  readonly owner: string;
  /** ファイル(製品の木の根からの相対)。 */
  readonly file: string;
  /** このファイルが値で引いてよい包みの名前。 */
  readonly packages: readonly string[];
}

/** 外へ送る口の置き場(閉じた表の口と、それを値で引いてよいディレクトリ)。 */
export interface OutboundHomes {
  /** 外へ送る口のモジュール(`outbound-primitives.ts` の表そのもの)。 */
  readonly primitives: readonly string[];
  /** 置き場(製品の木の根からの相対。外部連携の `adapter_root` の全部と土台)。 */
  readonly homes: readonly string[];
}

/** 表の全体。 */
export interface SdkHomesTable {
  readonly homes: readonly SdkHomeRow[];
  readonly clientUi: readonly SdkClientUiRow[];
  readonly outbound: OutboundHomes;
}

/**
 * 製品の根からの相対にする(根の外のパスはそのまま返す — 宣言の誤りは X1 が言う)。
 *
 * @param appRoot 製品の根(リポジトリルート相対)
 * @param repoPath リポジトリルート相対のパス
 * @returns 製品の根からの相対
 */
function underApp(appRoot: string, repoPath: string): string {
  return repoPath.startsWith(`${appRoot}/`) ? repoPath.slice(appRoot.length + 1) : repoPath;
}

/**
 * 外部連携カタログと置き場の配置から、SDK の置き場の表を組む。
 *
 * @param catalog 外部連携カタログ(無ければ null)
 * @param ctx 生成の文脈(配置と製品の根)
 * @returns 表(宣言順)
 */
export function sdkHomesOf(catalog: ExternalCatalogSpec | null, ctx: Pick<GenerateContext, 'layout' | 'roots'>): SdkHomesTable {
  const appRoot = ctx.roots.app;
  if (appRoot === null) return { homes: [], clientUi: [], outbound: { primitives: OUTBOUND_PRIMITIVE_MODULES, homes: [] } };
  const services = catalog?.vocabulary.service ?? [];
  const homes: SdkHomeRow[] = [
    ...services
      .filter((term) => term.sdkPackages.length > 0)
      .map((term) => ({ owner: `service:${term.id}`, dir: underApp(appRoot, term.adapterRoot), packages: term.sdkPackages })),
    ...productSdkHomes(ctx.layout, '').map((home) => ({ owner: `base:${home.path}`, dir: home.path, packages: home.packages })),
  ];
  const clientUi = services.flatMap((term) =>
    term.clientUi.map((row) => ({ owner: `service:${term.id}`, file: underApp(appRoot, row.file), packages: row.packages })),
  );
  const bases = productSdkHomes(ctx.layout, '').map((home) => home.path);
  const outboundHomes = [...new Set([...services.map((term) => underApp(appRoot, term.adapterRoot)), ...bases])];
  return { homes, clientUi, outbound: { primitives: OUTBOUND_PRIMITIVE_MODULES, homes: outboundHomes } };
}

/** 生成物の出力先(リポジトリルート相対)。 */
const outputFile = (ctx: GenerateContext): string => generatedFile(ctx.roots, 'sdk-homes.json');

/** SDK の置き場の表の生成器。 */
export const sdkHomesGenerator: DocGenerator = {
  id: 'code-sdk-homes',

  generate(_model: SpecModel, ctx: GenerateContext): GeneratedSection[] {
    if (ctx.roots.app === null) return [];
    const table = sdkHomesOf(ctx.external?.catalog ?? null, ctx);
    const body = {
      $generated:
        'AUTO-GENERATED by `npm run generate` — 手編集禁止。正は external_spec の vocabulary.service[].sdk_packages / client_ui / adapter_root と置き場の配置の土台の sdkPackages(外へ送る口の表は spec-tools の outbound-primitives.ts)。',
      homes: table.homes,
      clientUi: table.clientUi,
      outbound: table.outbound,
    };
    return [{ file: outputFile(ctx), content: `${JSON.stringify(body, null, 2)}\n`, wholeFile: true }];
  },
};
