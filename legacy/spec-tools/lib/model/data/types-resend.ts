/**
 * data_table の `resend`(作成の**冪等な再送**で、既存の行を返すかどうか)の宣言の型。
 *
 * 作成の RPC は呼ぶ側が渡す id(`p_id`)を冪等キーにし、同じ id の行が既にあれば
 * 「同じ呼び出しの再送」として扱う。ところが id は**行の中身を問わずに選べる鍵**である ——
 * 他人の行の id を渡した呼び出しに既存の行をそのまま返すと、その中身が漏れる。
 * そこで「返してよいか」を表ごとに宣言させる(書いていなければ T6 / Y12 が名指しで止める)。
 *
 * - `returnsExisting: true` + `creator` … 再送で既存の行を返す。返すのは**作成者の欄(`creator`)が実行者と
 *   一致する行だけ**。一致しなければ中身を返さず競合(`UC409`)。
 * - `returnsExisting: true`(`creator` なし)… 再送で既存の行を返す。返すのは**その作成の監査ログの行(`domain_events`。
 *   同じ id・同じ操作)の実行者が今回の実行者と一致する行だけ**(点検 20 回目 B20-1。作成者の欄を持たない表でも、作成 RPC は
 *   同じ txn で必ず監査ログを書くので、誰の作成かは行の外に残っている)。未ログインの作成は実行者が null どうしで一致し、
 *   鍵(推測できない UUID。送った画面だけが持つ)が範囲になる。
 * - `returnsExisting: false` … 再送で既存の行を返さない。同じ id の行があれば常に競合(`UC409`)。
 *
 * 返すどちらの方針でも、**同じ鍵で入力が違う**再送は返さず、拒否の語 `resend_input_mismatch`(UC412)で断る(1 回目が書けて
 * いるので行は増やさず、2 回目の入力を「書けた」と偽らない)。
 *
 * 置き場を表に取るのは、単発の作成 RPC と、その表を錨にする複合 RPC が**同じ 1 つの答え**を
 * 持つべきだからである(片方だけ返すと、もう片方の経路から同じ行が漏れる)。
 */

import type { SourceLocation } from '../types.js';

/** 作成の冪等な再送の宣言(data_table の `resend`)。 */
export interface DataResendDecl {
  /** 再送で既存の行を返すか。 */
  readonly returnsExisting: boolean;
  /**
   * 作成者の欄(その表の列名)。`returnsExisting: true` のときだけ書ける(書かなければ監査ログの実行者で確かめる)。
   * 作成の RPC が**実行者そのもので埋める列**でなければならない(T6 / Y12 が引数の役目から確かめる)。
   */
  readonly creator?: string;
  /** 宣言の位置(指摘の場所に使う)。 */
  readonly location: SourceLocation;
}
