import { describe, expect, it } from 'vitest';

import { transitionTableGenerator } from '../../../../lib/generate/render/code-transitions.js';
import type { GenerateContext } from '../../../../lib/gen-kit/generator.js';
import type { StateMachineSpec } from '../../../../lib/model/types.js';
import {
  aggregate,
  effect,
  event,
  loc,
  machine,
  specModel,
  stubGuards,
} from '../../../helpers/model-builder.js';
import { GEN_CTX } from '../../../helpers/generate-context.js';
import { TEST_ROOTS } from '../../../helpers/product-roots.js';
import { TEST_PLATFORM, TEST_LAYOUT } from '../../../helpers/platform.js';
import { NO_GATES } from '../../../helpers/generate-context.js';

/** 1 状態機械だけのモデルを生成し、その本文を返す。 */
function generateOne(spec: StateMachineSpec, ctx: GenerateContext = GEN_CTX): string {
  const model = specModel([aggregate(spec.machine, { stateMachines: [spec] })]);
  const section = transitionTableGenerator.generate(model, ctx)[0];
  if (section === undefined) throw new Error('セクションが生成されませんでした');
  return section.content;
}

/** ガード式 1 本だけを持つ機械を作り、生成されたガードのデータ部分を返す。 */
function guardDataOf(guard: string, ctx: GenerateContext = GEN_CTX): string {
  const content = generateOne(
    machine('entry', {
      states: ['draft', 'submitted'],
      initial: 'draft',
      events: [event('submit', { from: ['draft'], to: 'submitted', guard })],
    }),
    ctx,
  );
  const body = content.split('guard: ')[1]?.split('\n      guardSource:')[0];
  if (body === undefined) throw new Error(`guard が出力されていません:\n${content}`);
  return body;
}

describe('transitionTableGenerator', () => {
  it('ファイル全体モードで app/src/domain/generated/{machine}.transitions.ts を出力する', () => {
    const model = specModel([
      aggregate('entry', {
        stateMachines: [machine('entry', { states: ['draft'], initial: 'draft' })],
      }),
      aggregate('workshop', {
        stateMachines: [machine('workshop', { states: ['draft'], initial: 'draft' })],
      }),
    ]);

    const sections = transitionTableGenerator.generate(model, GEN_CTX);

    expect(sections.map((s) => s.file)).toEqual([
      'app/src/domain/generated/entry.transitions.ts',
      'app/src/domain/generated/workshop.transitions.ts',
    ]);
    expect(sections[0]?.wholeFile).toBe(true);
    expect(sections[0]?.marker).toBeUndefined();
  });

  it('AUTO-GENERATED ヘッダ・エンジン型の import・satisfies 付きの named export を出す', () => {
    const content = generateOne(
      machine('entry', { states: ['draft', 'submitted'], initial: 'draft', final: ['submitted'] }),
    );

    expect(content.startsWith('/**\n * AUTO-GENERATED by `npm run generate` — 手編集禁止。')).toBe(true);
    expect(content).toContain(' *   - docs/specs/domain/entry/states.md');
    expect(content).toContain("import type { MachineTable } from '@kaninabe/runtime/engine/types';");
    expect(content).toContain('export const entryMachine = deepFreeze({');
    expect(content).toContain('} as const satisfies MachineTable);');
    expect(content).toContain("  machine: 'entry',");
    expect(content).toContain("  states: ['draft', 'submitted'],");
    expect(content).toContain("  initial: 'draft',");
    expect(content).toContain("  final: ['submitted'],");
  });

  it('イベントを event / from / to / by / effects を持つ遷移に写像する', () => {
    const content = generateOne(
      machine('entry', {
        states: ['draft', 'submitted', 'withdrawn'],
        initial: 'draft',
        events: [
          event('withdraw', {
            from: ['draft', 'submitted'],
            to: 'withdrawn',
            by: ['performer', 'organizer'],
          }),
        ],
      }),
    );

    expect(content).toContain("      event: 'withdraw',");
    expect(content).toContain("      from: ['draft', 'submitted'],");
    expect(content).toContain("      to: 'withdrawn',");
    expect(content).toContain("      by: ['performer', 'organizer'],");
    expect(content).toContain('      effects: [],');
    expect(content).not.toContain('guardSource');
    expect(content).not.toContain('otherwiseForbidden');
  });

  it('otherwise_forbidden の理由文を otherwiseForbidden として運ぶ(実装が拒否の理由文に使う)', () => {
    const content = generateOne(
      machine('entry', {
        states: ['draft', 'submitted'],
        initial: 'draft',
        events: [
          event('submit', {
            from: ['draft'],
            to: 'submitted',
            otherwiseForbidden: '提出は下書きからのみ。確定後の再提出は新規エントリーとして扱う',
          }),
        ],
      }),
    );

    expect(content).toContain(
      "      otherwiseForbidden: '提出は下書きからのみ。確定後の再提出は新規エントリーとして扱う',",
    );
  });

  it('otherwise_forbidden はガードの直後・effects の直前に置く(仕様の並び順を保つ)', () => {
    const content = generateOne(
      machine('entry', {
        states: ['draft', 'submitted'],
        initial: 'draft',
        events: [
          event('submit', {
            from: ['draft'],
            to: 'submitted',
            guard: 'workshop.state == accepting',
            otherwiseForbidden: '提出は下書きからのみ',
          }),
        ],
      }),
    );

    expect(content).toContain(
      [
        "      guardSource: 'workshop.state == accepting',",
        "      otherwiseForbidden: '提出は下書きからのみ',",
        '      effects: [],',
      ].join('\n'),
    );
  });

  it('effects はイベント単位に集約し、宣言順を保つ', () => {
    const content = generateOne(
      machine('entry', {
        states: ['draft', 'submitted'],
        initial: 'draft',
        events: [
          event('submit', { from: ['draft'], to: 'submitted' }),
          event('revise', { from: ['submitted'], to: 'draft' }),
        ],
        effects: [
          effect('submit', ['notify_organizer_new_entry']),
          effect('submit', ['audit_submit']),
          effect('revise', []),
        ],
      }),
    );

    expect(content).toContain("      effects: ['notify_organizer_new_entry', 'audit_submit'],");
    expect(content.match(/effects: \[\],/g)).toHaveLength(1);
  });

  it('compare(リテラル右辺)を GuardExprData に写像し、原文を guardSource に残す', () => {
    const content = generateOne(
      machine('entry', {
        states: ['draft', 'submitted'],
        initial: 'draft',
        events: [
          event('submit', { from: ['draft'], to: 'submitted', guard: 'workshop.state == accepting' }),
        ],
      }),
    );

    expect(content).toContain("        kind: 'compare',");
    expect(content).toContain("        path: 'workshop.state',");
    expect(content).toContain("        op: '==',");
    expect(content).toContain("          kind: 'literal',");
    expect(content).toContain("          value: 'accepting',");
    expect(content).toContain("      guardSource: 'workshop.state == accepting',");
  });

  it('compare の右辺がパスなら {kind:\'path\'} にする', () => {
    expect(guardDataOf('now >= workshop.entry_deadline')).toContain("kind: 'path',");
    expect(guardDataOf('now >= workshop.entry_deadline')).toContain("path: 'workshop.entry_deadline',");
    expect(guardDataOf('entry.performer_id == actor.id')).toContain("path: 'actor.id',");
  });

  it('数値リテラルは数値のまま埋め込む', () => {
    expect(guardDataOf('entry.duration_min <= 60')).toContain('value: 60,');
  });

  it('in / not in / contains を写像する(not in は not(in) の入れ子のまま)', () => {
    const inData = guardDataOf('workshop.state in [accepting, closed]');
    expect(inData).toContain("kind: 'in',");
    expect(inData).toContain("path: 'workshop.state',");
    expect(inData).toContain("values: ['accepting', 'closed'],");

    const notInData = guardDataOf('workshop.state not in [accepting, closed]');
    expect(notInData).toContain("kind: 'not',");
    expect(notInData).toContain('operand: {');
    expect(notInData).toContain("kind: 'in',");

    const containsData = guardDataOf('workshop.organizer_ids contains actor.id');
    expect(containsData).toContain("kind: 'contains',");
    expect(containsData).toContain("path: 'workshop.organizer_ids',");
    expect(containsData).toContain("ref: 'actor.id',");
  });

  it('and / or を left・right の入れ子に合成する', () => {
    const data = guardDataOf('workshop.state == accepting and now < workshop.starts_at');

    expect(data).toContain("kind: 'and',");
    expect(data).toContain('left: {');
    expect(data).toContain('right: {');
    expect(data).toContain("path: 'workshop.state',");
    expect(data).toContain("path: 'now',");
  });

  it('パース不能なガードは throw せず guard 省略 + guardSource だけに縮退する', () => {
    const broken: GenerateContext = {
      guards: { ...stubGuards(), parse: () => ({ ok: false, error: { message: 'ng', offset: 0 } }) },
      roots: TEST_ROOTS, platform: TEST_PLATFORM, layout: TEST_LAYOUT, gates: NO_GATES,
    };
    const content = generateOne(
      machine('entry', {
        states: ['draft', 'submitted'],
        initial: 'draft',
        events: [event('submit', { from: ['draft'], to: 'submitted', guard: '??? broken ???' })],
      }),
      broken,
    );

    expect(content).not.toContain('guard: {');
    expect(content).toContain("      guardSource: '??? broken ???',");
  });

  it('終端状態とその補集合(非終端状態)を named export で出す', () => {
    const content = generateOne(
      machine('entry', {
        states: ['draft', 'submitted', 'accepted', 'rejected', 'withdrawn'],
        initial: 'draft',
        final: ['rejected', 'withdrawn'],
      }),
    );

    expect(content).toContain("export const entryFinalStates = deepFreeze(['rejected', 'withdrawn'] as const);");
    expect(content).toContain(
      "export const entryNonFinalStates = deepFreeze(['draft', 'submitted', 'accepted'] as const);",
    );
  });

  it('終端状態が無ければ非終端状態は全状態になる', () => {
    const content = generateOne(
      machine('entry', { states: ['draft', 'submitted'], initial: 'draft', final: [] }),
    );

    expect(content).toContain('export const entryFinalStates = deepFreeze([] as const);');
    expect(content).toContain("export const entryNonFinalStates = deepFreeze(['draft', 'submitted'] as const);");
  });

  it('不変条件が無ければアクティブ状態は出さない(仕様の外で「アクティブ」を決めない)', () => {
    const content = generateOne(
      machine('entry', { states: ['draft', 'submitted'], initial: 'draft', final: ['submitted'] }),
    );

    expect(content).not.toContain('export const entryActiveStates');
  });

  it('不変条件の where から導けたアクティブ状態は、根拠の仕様ごと出す', () => {
    const model = specModel([
      aggregate('entry', {
        stateMachines: [
          machine('entry', {
            states: ['draft', 'submitted', 'rejected'],
            initial: 'draft',
            final: ['rejected'],
          }),
        ],
        invariants: {
          invariants: [
            {
              id: 'INV-ENTRY-001',
              statement: 'アクティブなエントリーは 1 つ',
              entities: ['entry'],
              formal: {
                kind: 'uniqueness',
                keys: ['workshop_id'],
                where: 'entry.state not in [rejected]',
              },
              enforcedBy: [],
              location: loc('docs/specs/domain/entry/invariants.md', 'invariants.INV-ENTRY-001'),
            },
          ],
          location: loc('docs/specs/domain/entry/invariants.md'),
        },
      }),
    ]);

    const content = transitionTableGenerator.generate(model, GEN_CTX)[0]?.content ?? '';

    expect(content).toContain("export const entryActiveStates = deepFreeze(['draft', 'submitted'] as const);");
    expect(content).toContain('正は INV-ENTRY-001 の where 句');
    // 導出元の仕様がヘッダの「正」の一覧に加わる。
    expect(content).toContain(' *   - docs/specs/domain/entry/invariants.md');
  });

  it('同じモデルからは同じ出力になる(生成物の決定性 — ADR-0006)', () => {
    const spec = machine('entry', {
      states: ['draft', 'submitted'],
      initial: 'draft',
      events: [event('submit', { from: ['draft'], to: 'submitted', guard: 'workshop.state == accepting' })],
      effects: [effect('submit', ['notify_organizer_new_entry'])],
    });

    expect(generateOne(spec)).toBe(generateOne(spec));
  });
});
