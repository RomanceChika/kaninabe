/**
 * 表の権限の migration(`lib/sql/grants-migration.ts`)のユニットテスト。
 *
 * 規約網羅(design/ddl-reissue-free-changes.md §4 の C′ / ARCH-SP-BE-0001 §テーブル仕様):
 *   - 母集合は **data_table の全数**(形の正が無い内部テーブルも載る)
 *   - 特権ロールには**どの表でも同じ 4 権限**(`truncate` は含まない)
 *   - surface のロールを剥奪するのは**ポリシーの migration を持たない表だけ**(二重に出さない)
 *   - 付与先(`service_role`)からも**先に剥奪する**(Supabase の既定権限を落とすため)
 *   - **表の数だけ 2 行**であり、表が増えても migration は 1 本のまま
 *   - 表ごとの 2 行は**その表が在るときだけ**流す(存在ガード。連番の前後に寄りかからない ——
 *     番号で保証していたあいだ、表の DDL の再発行ごとにバイト同一の migration が 1 本増えた)
 */

import { FOREIGN_PLATFORM, leaksSupabaseSpelling, TEST_PLATFORM } from '../../helpers/platform.js';
import { describe, expect, it } from 'vitest';
import { buildGrantsMigration, grantPlans } from '../../../lib/sql/grants-migration.js';
import { dataTable } from '../../helpers/data-builder.js';

/** ポリシーを持つ表(surface のロールの権限はあちらが持つ)。 */
const WITH_POLICIES = dataTable('bookings', {
  entity: 'booking',
  ddlMigration: '20260912120201_ddl_bookings.sql',
  policiesMigration: '20260912120301_policies_bookings.sql',
});

/** 仕組みが自分で持つ表(ポリシーを 1 本も持たない)。 */
const FRAMEWORK = dataTable('domain_events', {
  internal: true,
  framework: 'domain_events',
  ddlMigration: '20260912120202_ddl_domain_events.sql',
});

/** 形の正がどこにも無い内部テーブル(`ddl_migration` を宣言できない)。 */
const INTERNAL = dataTable('ai_usage', { internal: true });

const TABLES = [WITH_POLICIES, FRAMEWORK, INTERNAL];

describe('表の権限の計画', () => {
  it('母集合は data_table の全数である(形の正が無い表も載る)', () => {
    expect(grantPlans(TABLES, TEST_PLATFORM).map((plan) => plan.table)).toEqual([
      'ai_usage',
      'bookings',
      'domain_events',
    ]);
  });

  it('特権ロールにはどの表でも同じ 4 権限だけを与える(truncate は与えない)', () => {
    for (const plan of grantPlans(TABLES, TEST_PLATFORM)) {
      expect(plan.grant.to).toBe('service_role');
      expect(plan.grant.privileges).toEqual(['select', 'insert', 'update', 'delete']);
    }
  });

  it('surface のロールを剥奪するのはポリシーを持たない表だけ(二重に出さない)', () => {
    const byTable = Object.fromEntries(
      grantPlans(TABLES, TEST_PLATFORM).map((plan) => [plan.table, plan.grant.revokeFrom]),
    );
    expect(byTable['bookings']).toEqual([]);
    expect(byTable['domain_events']).toEqual(['anon', 'authenticated']);
    expect(byTable['ai_usage']).toEqual(['anon', 'authenticated']);
  });
});

describe('表の権限の migration', () => {
  const sql = buildGrantsMigration(grantPlans(TABLES, TEST_PLATFORM));

  it('AUTO-GENERATED ヘッダと、名前を新しくする規則が先頭に載る', () => {
    expect(sql).toContain('-- AUTO-GENERATED by `npm run generate` — 手編集禁止。');
    expect(sql).toContain('-- (api_spec の grants_migration)。載る表は data_table の全数である。');
  });

  it('ポリシーを持つ表は特権ロールだけを触る(付与先からも先に剥奪する)', () => {
    expect(sql).toContain('revoke all on public.bookings from service_role;');
    expect(sql).toContain('grant select, insert, update, delete on public.bookings to service_role;');
  });

  it('表ごとの 2 行は存在ガードの中に出る(表がまだ無い DB に当たっても落ちない)', () => {
    expect(sql).toContain(
      [
        'do $$',
        'begin',
        "    if to_regclass('public.bookings') is not null then",
        '        revoke all on public.bookings from service_role;',
        '        grant select, insert, update, delete on public.bookings to service_role;',
        '    end if;',
        'end',
        '$$;',
      ].join('\n'),
    );
    // 表の数だけ do ブロックが出る(1 つにまとめない —— 1 枚ずつ独立に読めるようにする)。
    expect(sql.match(/^do \$\$$/gmu)).toHaveLength(TABLES.length);
    expect(sql.match(/^ {4}if to_regclass\('public\.[a-z_]+'\) is not null then$/gmu)).toHaveLength(
      TABLES.length,
    );
  });

  it('ポリシーを持たない表は surface のロールごと剥奪する', () => {
    expect(sql).toContain('revoke all on public.domain_events from anon, authenticated, service_role;');
    expect(sql).toContain('revoke all on public.ai_usage from anon, authenticated, service_role;');
  });

  it('節は 2 つで、どの表の権限も 2 行ずつ出る(表が増えても migration は 1 本)', () => {
    expect(sql.match(/^-- 権限。/gmu)).toHaveLength(2);
    expect(sql.match(/^ {8}revoke all on /gmu)).toHaveLength(TABLES.length);
    expect(sql.match(/^ {8}grant /gmu)).toHaveLength(TABLES.length);
  });

  it('表が 1 枚も無ければ節ごと出ない(見出しだけのファイルを作らない)', () => {
    const empty = buildGrantsMigration([]);
    expect(empty).not.toContain('revoke all on');
    expect(empty).not.toContain('-- 権限。');
  });
});

describe('別のプラットフォームの設定を渡すと(権限の本文は設定の中身を知らない)', () => {
  const plans = grantPlans(TABLES, FOREIGN_PLATFORM);
  const sql = buildGrantsMigration(plans);

  it('剥奪する一般利用者と、与える特権ロールが設定から引かれる', () => {
    expect(plans.map((plan) => plan.grant.to)).toEqual(['worker', 'worker', 'worker']);
    expect(plans.find((plan) => plan.table === 'domain_events')?.grant.revokeFrom).toEqual(['visitor', 'signed_in']);
    expect(sql).toContain('revoke all on public.domain_events from visitor, signed_in, worker;');
    expect(sql).toContain('grant select, insert, update, delete on public.domain_events to worker;');
  });

  it('Supabase の綴りが 1 つも残らない', () => {
    expect(leaksSupabaseSpelling(sql)).toBe(false);
    expect(leaksSupabaseSpelling(buildGrantsMigration(grantPlans(TABLES, TEST_PLATFORM)))).toBe(true);
  });
});
