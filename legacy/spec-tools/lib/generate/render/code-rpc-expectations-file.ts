/**
 * RPC 本文の期待表(生成物の置き場の `rpc-expectations.ts`)の**ファイルの字面**(型の宣言と定数の書き出し)。
 *
 * 期待の中身は `code-rpc-expectations.ts` が仕様から組み立てる。ここは組み立てた値をファイルに写すだけで、
 * 何を突き合わせるかは決めない(型の欄の説明が、統合テスト rpc-parity が読む契約の正である)。
 *
 * 規約どおりファイル I/O はせず、文字列を返す純粋関数である(scripts-code-quality.md)。
 */

import type { LiteralValue } from '../../gen-kit/code-emit.js';
import { DEEP_FREEZE_HELPER, docComment, generatedHeader, renderLiteral } from '../../gen-kit/code-emit.js';
import { frozen } from '../../gen-kit/frozen-constants.js';

/** 期待表のファイル全体を組み立てる。 */
export function renderRpcExpectationsFile(
  byName: Readonly<Record<string, LiteralValue>>,
  personal: Readonly<Record<string, LiteralValue>>,
  specFiles: readonly string[],
  addressees: Readonly<Record<string, LiteralValue>> = {},
): string {
  return [
    generatedHeader(specFiles),
    '',
    ...DEEP_FREEZE_HELPER,
    '',
    docComment(['書き込み RPC の形。定型 4 形と、定型に乗らない composite。']),
    "export type RpcShape = 'transition' | 'create' | 'update' | 'delete' | 'composite';",
    '',
    docComment([
      '空を渡された列に RPC が要求される扱い（値域）。',
      '',
      '`assign` = そのまま代入（空が空として入る）、`coalesce` = 空なら触れない。',
    ]),
    "export type ColumnContract = 'assign' | 'coalesce';",
    '',
    docComment(['RPC 1 本に対する本文の期待（突き合わせない項目はキーを持たない）。']),
    'export interface RpcExpectation {',
    '  /** 帰属する表（この関数の持ち場）。 */',
    '  readonly table: string;',
    '  /** 形。composite は本文の意味を突き合わせない。 */',
    '  readonly shape: RpcShape;',
    '  /** 帰属表のほかに書き込む表（data_table の also_writes）。全 RPC で突合する。 */',
    '  readonly alsoWrites: readonly string[];',
    '  /** also_writes の各表に宣言された書き込みの種類（insert / update / delete / scrub。scrub は本文では update）。本文が行う書き込みと突合する。 */',
    '  readonly alsoWriteKinds: Readonly<Record<string, readonly (\'insert\' | \'update\' | \'delete\' | \'scrub\')[]>>;',
    '  /** 帰属表への書き込みの種類（data_table の self_writes。定型 4 形は形が決める）。外部キーの連鎖で起きる分も含めて本文と突合する。 */',
    '  readonly selfWriteKinds: readonly (\'insert\' | \'update\' | \'delete\' | \'scrub\')[];',
    '  /** 消去が表のどの参照の道で行に届くか（scrub_via）。本文の一致は統合テストが見る。 */',
    '  readonly scrubVia: Readonly<Record<string, readonly string[]>>;',
    '  /** self_writes を宣言したか（宣言した関数だけ、帰属表の update の set 句に個人列があれば scrub を要求する）。 */',
    '  readonly selfWritesDeclared: boolean;',
    '  /** この RPC を realized_by で名指す効果の ID。本文に効果 ID のリテラル（目印）があることを要求する。 */',
    '  readonly realizes: readonly string[];',
    '  /** 本文が呼ぶ他の関数（data_table の calls）。本文の呼び出しと一致すること（宣言の無い呼び出しは読めないので赤）。 */',
    '  readonly calls: readonly string[];',
    '  /** 本文が動的 SQL（execute）を使うと宣言したか（data_table の dynamic_sql）。宣言の無い execute は読めないので赤。 */',
    '  readonly dynamicSql: boolean;',
    '  /**',
    '   * 本文を生成した migration のファイル名（`functions[].migration`）。',
    '   *',
    '   * **これがあるときは本文が生成物である** —— 突合は「生成した SQL と実 DB の本文が',
    '   * 一致するか」の 1 つだけになり、断片ごとの目（許可列・OCC・空の扱い）は要らない',
    '   * （生成器が宣言から作っているので、ずれようが無い）。無いものは本文が手書きであり、',
    '   * 従来どおり断片を突き合わせる。',
    '   */',
    '  readonly migration?: string;',
    '  /**',
    '   * 書き換えてよい列（`shape: update` のみ）= access_spec の writes に現れる列の和。',
    '   *',
    '   * RPC 側の列の固定は第二防衛線である（第一は operation がエンジンに照会する側）。',
    '   * この一覧が宣言に追随しているかを見る機械が無かったのが E3 第3段で見つかった穴である。',
    '   */',
    '  readonly columns?: readonly string[];',
    '  /**',
    '   * 作成 RPC が `p_values` から入れる列（`shape: create` のみ）。',
    '   *',
    '   * 列の既定値（`defaults`）の突合を**双方向**にするための母集合である —— この一覧に載る',
    '   * 列が DB に既定値を持つなら、宣言にも無ければならない（宣言が無いと生成本文から',
    '   * `coalesce` が消え、鍵の無い日に NULL が入る）。母集合を全列にすると `id` / `state` /',
    '   * `created_at` の導出分がノイズになるので、作成が実際に入れる列だけに絞る。',
    '   */',
    '  readonly valueColumns?: readonly string[];',
    '  /**',
    '   * 判断時の状態を条件に書き込むか（`composite` 以外の 4 形）。',
    '   *',
    '   * 遷移は無条件に真。ほかの 3 形は `access_spec` の対応する規則に `when` があるかで決まる',
    '   * （条件が 1 本も無い操作には「古びうる判断」が存在しない）。',
    '   */',
    '  readonly optimisticLock?: boolean;',
    '  /**',
    '   * 遷移 RPC が受け取る自集約の列について、**空を渡されたときの扱い**（`shape: transition` のみ）。',
    '   *',
    '   * 鍵は**ドメインイベント ID**（`{機械}.{イベント}`）で、値はその遷移が列ごとに要求する扱い。',
    '   * `assign` = そのまま代入する（空が空として入る。state_spec の `clears` を実現する）、',
    '   * `coalesce` = 空なら触れない（`coalesce(p_x, x)`）。宣言がイベント単位なので期待も',
    '   * イベント単位で持つ —— 列単位に潰すと「ある遷移は空にする / 別の遷移は触れない」同じ列が',
    '   * 黙って代入になり、触れないはずの遷移がその列を消す。',
    '   */',
    '  readonly columnContracts?: Readonly<Record<string, Readonly<Record<string, ColumnContract>>>>;',
    '  /**',
    '   * `records_actor` の列 → その列の縛りの代入文の字面（`shape: transition` のみ）。本文は書き込みの前に',
    '   * `p_{列} := case when p_event_id in (…) then p_actor_id … else null end` で引数を縛る（呼び手の値で他人の行の持ち主を据え替えない）。',
    '   * rpc-parity はこの文がちょうど 1 回・最初の `update` より前にあることを見る（else の枝・文の位置まで）。',
    '   */',
    '  readonly actorBound?: Readonly<Record<string, string>>;',
    '  /**',
    '   * 本文が手書きの作成 RPC の、再送の入力の比べ（表が `resend.returns_existing: true` のときだけ。点検 20 回目 B20-1）。',
    '   * 生成の作成 RPC は再送の枝を 1 か所から出すが、手書きの本文はそこを通らない。rpc-parity は本文に拒否の語 `word` と、',
    '   * `compared` の各列の比べ（`.{列} is distinct from`）があることを見る（同じ鍵で入力の違う再送に 1 回目の行を返さない）。',
    '   * `signal` は再送で既存の行を返すときに立てる印の設定の名前（点検 22 回目 A22-1。保存点の複合 RPC がこれで以降の手順を実行しない）。',
    '   */',
    '  readonly resendInput?: { readonly word: string; readonly compared: readonly string[]; readonly signal: string; readonly deleted: string };',
    '  readonly digestAnchors?: readonly { readonly event: string; readonly table: string; readonly branches: readonly { readonly from: string; readonly column: string; readonly reverse?: boolean; readonly up: string }[]; readonly removable: boolean }[];',
    '}',
    '',
    docComment([
      '関数名 → 本文の期待（`data_table` の functions と access_spec の writes の写し）。',
      '',
      '統合テスト（rpc-parity）が実 DB の `pg_get_functiondef` から意味のある断片を抜き出して',
      '突き合わせる。**本文の完全一致は見ない** —— 空白・コメント・整形の差で落ちる比較は',
      '脆すぎるためで、見るのは「宣言と食い違ったら業務上の意味が変わる」ところだけである。',
      '',
      'migration を生成物で置き換えないのは、migration が**追記専用の歴史**だからである',
      '（適用済みの SQL を書き換えると DB と食い違う）。新しい定型 RPC を書くときは、',
      'この表が期待する形をそのまま SQL に写す（server-actions.md §定型 RPC）。',
    ]),
    `export const rpcExpectations = ${frozen(`${renderLiteral(byName)} as const satisfies Readonly<Record<string, RpcExpectation>>`)};`,
    '',
    docComment([
      '同じ表を「関数名で引ける形」にしたもの。中身は上の定数と同一で、型だけが広い。',
      '突合テストは関数名を変数で回すため、リテラル型のままだと呼び出し側でキャストが要る。',
    ]),
    'export const rpcExpectationsByName: Readonly<Record<string, RpcExpectation>> = rpcExpectations;',
    '',
    docComment([
      '表 → personal 列（entity_spec の personal: true）。',
      '',
      'update の set 句がこの列を書き換える表は、宣言の種類に scrub（個人列を置き換えて消す）を要求する',
      '（rpc-parity。scrub を update と宣言すると、消去が destructive / touches_personal から黙って落ちる）。',
    ]),
    `export const personalColumnsByTable: Readonly<Record<string, readonly string[]>> = ${frozen(renderLiteral(personal))};`,
    '',
    docComment([
      '表 → 持ち主が宛先の個人列（data_table の erasure_addressee。列と、消去の対象の行からこの表を指す参照 `{表}.{列}`）。',
      '',
      '消去の本文が、対象の行の参照を読む文と、その値でこの表を書く文の組を持つことを統合テストが見る。',
    ]),
    `export const erasureAddressees: Readonly<Record<string, readonly { readonly column: string; readonly via: string }[]>> = ${frozen(renderLiteral(addressees))};`,
    '',
  ].join('\n');
}
