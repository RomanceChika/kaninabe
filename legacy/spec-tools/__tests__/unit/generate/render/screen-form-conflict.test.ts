/**
 * 競合の表示の共有部品(screen-form-conflict.ts)の字面。
 *
 * 確かめるのは、文言が仕組みの表(`FORM_WORDING`)から焼き込まれること・葉の名前が葉の表の定数と同じであること・
 * 見た目のクラスが既定のスタイルにあること・送信中は 2 択を止めること・アプリの語彙を 1 語も持たないこと。
 * 編集する表・更新フォームがこの部品を import する配線は、それぞれの生成物のテストが見る。
 */

import { describe, expect, it } from 'vitest';
import { FORM_WORDING } from '../../../../lib/messages/messages-screen.js';
import { renderScreenDefaultCss } from '../../../../lib/generate/render/screen-default-css.js';
import { CONFLICT_LEAVES } from '../../../../lib/generate/render/screen-draft.js';
import { FORM_CONFLICT_EXPORT, FORM_CONFLICT_FILE, renderFormConflict } from '../../../../lib/generate/render/screen-form-conflict.js';

describe('競合の表示の共有部品', () => {
  const text = renderFormConflict();

  it('置き場のファイル名と主 export は期待木の宣言と同じ', () => {
    expect(FORM_CONFLICT_FILE).toBe('form-conflict.tsx');
    expect(text).toContain(`export function ${FORM_CONFLICT_EXPORT}({ testId, pending, onResolve }: ${FORM_CONFLICT_EXPORT}Props) {`);
    expect(text.startsWith("'use client';")).toBe(true);
    expect(text).toContain('AUTO-GENERATED by `npm run generate`');
  });

  it('文言は仕組みの表(FORM_WORDING)から焼き込む', () => {
    expect(text).toContain(`const CONFLICT_MESSAGE = '${FORM_WORDING.conflict()}';`);
    expect(text).toContain(`const TAKE_THEIRS_LABEL = '${FORM_WORDING.take_theirs()}';`);
    expect(text).toContain(`const KEEP_MINE_LABEL = '${FORM_WORDING.keep_mine()}';`);
  });

  it('葉の名前は葉の表の定数と同じで、知らせと 2 択が呼び側の接頭辞の下に付く', () => {
    for (const leaf of CONFLICT_LEAVES) expect(text).toContain('data-testid={`${testId}.' + leaf + '`}');
    expect(text).toContain("onClick={() => onResolve('theirs')}");
    expect(text).toContain("onClick={() => onResolve('mine')}");
  });

  it('送信中は 2 択を押せず、見た目は既定のスタイルのクラスを当てる', () => {
    expect(text.match(/disabled=\{pending\}/g)).toHaveLength(2);
    expect(text).toContain("import styles from './default.module.css';");
    expect(text).toContain('className={styles.screenConflict}');
    expect(renderScreenDefaultCss()).toContain('.screenConflict {');
  });

  it('判定も解決も持たない(型だけを読む)・同じ入力なら同じ文字列', () => {
    expect(text).toContain("import type { ConflictChoice } from '@kaninabe/runtime/form-refresh';");
    expect(text).not.toContain('reconcileFormDraft');
    expect(text).not.toContain('useState');
    expect(renderFormConflict()).toBe(text);
  });
});
