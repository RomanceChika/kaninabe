/**
 * ハンドブックの CSS 資材(docs/book/assets/{tokens.css,ui.css})の生成器。
 *
 * ハンドブックの図(レイアウト図・色スウォッチ)とパーツ見本は、**このシステム自身の意匠**で
 * 描かれてこそ意味がある。そのために 2 枚の CSS を book の配下へ吐き、HTML の本が
 * 読み込む:
 *   - tokens.css … トークン仕様からの写像。実装側の生成物(app/src/domain/generated/tokens.css)と
 *     同じレンダラーで出すので、同じ仕様から必ず同じ値になる
 *   - ui.css    … 実装の globals.css + ui.module.css を `.parts-demo` 配下へスコープした写し。
 *     コピー元は CLI が読んで文脈(book)に載せる(生成器は I/O をしない規約)
 *
 * どちらも wholeFile の生成物なので、コピー元とのズレは generate:check(鮮度チェック)が
 * そのまま検出する。
 */

import { blockCommentText } from '../../../kernel/safe-text.js';
import type { SpecModel } from '../../../model/types.js';
import type { DocGenerator, GeneratedSection, GenerateContext } from '../../../gen-kit/generator.js';
import { renderTokensCss } from '../code-design-tokens.js';
import { scopeCss } from './ui-css.js';
import { bookFile } from './chapters.js';
import { summaryTableOf } from '../../../semantics/reading-axioms.js';
import { appResourcePath } from '../../../model/product/layout.js';
import { GLOBALS_CSS_SOURCE, UI_CSS_SOURCE } from '../../book-input-sources.js';
import { screenPartFile } from '../screen-part-placement.js';
import { SCREEN_DEFAULT_CSS_FILE, renderScreenDefaultCss } from '../screen-default-css.js';
import { buildScreenForms } from '../screen-form-plan.js';

/**
 * 見本コンテナのセレクタ(テーマ CSS・見本マークアップと共有する取り決め)。
 *
 * クラスを 2 回重ねるのは詳細度のため — 文書スタイルと
 * 見本側の打ち消し(`.parts-demo table` 等)より必ず強くし、見本の中では
 * **アプリの CSS が最後に勝つ**順序をセレクタだけで固定する(読み込み順に依存させない)。
 */
export const PARTS_DEMO_SCOPE = '.parts-demo.parts-demo';

/**
 * SSR プレビューの舞台のセレクタ(画面カードの「実物」の器)。
 *
 * パーツ見本と別のスコープを持つのは、器の意匠が違うから(見本は 1 部品ぶんの小さな舞台、
 * プレビューはページ 1 枚ぶんの舞台)である。中身に当てる CSS は同じ実装ファイルの写しで、
 * `scopeCss` を 2 回通す。
 */
export const SCREEN_PREVIEW_SCOPE = '.screen-preview.screen-preview';

/**
 * ロゴの写し(`docs/book/` からの相対パス)。
 *
 * `brand-icon.ts` が README・design 章の `<img>` の `src` に使う。`assets/` 直下に
 * 置くのは tokens.css / ui.css と同じ置き場の慣例に揃えるため。
 */
export const BRAND_ICON_FILE = 'assets/brand-icon.svg';

/**
 * 要約の文(章頭の 1 文・節の要約・段の場面)と計算の例の表の行の写しの置き場(`docs/book/` からの相対パス)。
 *
 * 仕様の `summary` と `computes[].examples` を集めた写しで、`spec:diff` が基点の側と比べる元になる
 * (書き換わったかどうかが公理の側の差分)。文・例の正は仕様で、ここは写しである(ずれは generate:check が検出する)。
 */
export const SUMMARIES_FILE = 'assets/summaries.json';

/** スコープ済み CSS のヘッダ(生成物であることと、コピー元の宣言)。 */
function uiCssHeader(sources: readonly string[]): string {
  return [
    '/*',
    ' * AUTO-GENERATED by `npm run generate` — 手編集禁止。',
    ' *',
    ` * 次の実装 CSS を \`${PARTS_DEMO_SCOPE}\`(パーツ見本)と`,
    ` * \`${SCREEN_PREVIEW_SCOPE}\`(画面カードの SSR プレビュー)の配下へスコープした写しである。`,
    ' * 変更するときは実装側を編集してから再生成すること。',
    ...sources.map((source) => ` *   - ${blockCommentText(source)}`),
    ' */',
  ].join('\n');
}

/**
 * 既定のスタイル(画面の部品の生成物)の写し元の置き場(ヘッダに出す)。置き場は配置から引く。**黙って空のパスにしない**:
 * 実装の木があるのに配置が決められなければ前提の失敗(`screenPartFile` が先に見るべき検査を名指して止める)。実装の木を持たない製品は写し元が無い。
 */
function screenDefaultCssSource(ctx: GenerateContext): readonly string[] {
  const file = screenPartFile(ctx, SCREEN_DEFAULT_CSS_FILE, {
    what: 'ハンドブックの CSS 資材の写し元(画面の部品の既定のスタイル)',
    location: { file: bookFile(ctx.roots, 'assets/ui.css') },
  });
  return file === null ? [] : [file];
}

/** `app-resource` の写し元の置き場(ヘッダに出す)。実装の木が無く決められなければ 1 つも載せない(空文字の項目を作らない)。 */
function stylesheetSource(ctx: GenerateContext, relative: string): readonly string[] {
  const place = appResourcePath(ctx.layout, ctx.roots, relative);
  return place === null ? [] : [place];
}

/**
 * ハンドブックの CSS 資材を生成するジェネレーター。
 * 出力は docs/book/assets/tokens.css と docs/book/assets/ui.css(いずれもファイル全体)。
 */
export const bookAssetsGenerator: DocGenerator = {
  id: 'book-assets',

  generate(model: SpecModel, ctx: GenerateContext): GeneratedSection[] {
    const sections: GeneratedSection[] = [];
    sections.push({
      file: bookFile(ctx.roots, SUMMARIES_FILE),
      content: `${JSON.stringify(summaryTableOf(model, ctx.actions?.actions ?? []), null, 2)}\n`,
      wholeFile: true,
    });
    const spec = ctx.design?.spec;
    if (spec !== undefined && spec !== null) {
      sections.push({
        file: bookFile(ctx.roots, `assets/tokens.css`),
        content: renderTokensCss(spec),
        wholeFile: true,
      });
    }
    const brandIconSvg = ctx.book?.brandIconSvg;
    if (brandIconSvg !== undefined) {
      // 実装(app/src/app/icon.svg)の写し。VitePress は docs/ 配下しか静的配信しないので、
      // README・design 章から相対パスで <img> を出すにはここへコピーしておく必要がある
      // (tokens.css と同じ「コピー元とのズレは generate:check が検出する」写しの形)。
      sections.push({ file: bookFile(ctx.roots, `${BRAND_ICON_FILE}`), content: brandIconSvg, wholeFile: true });
    }
    const globals = ctx.book?.globalsCss;
    const uiCss = ctx.book?.uiCss;
    if (uiCss !== undefined) {
      // 画面の部品の生成物(フォーム)が当てる既定のスタイルも含める(カードが素の見た目にならないように)。
      // 生成物そのものはディスクから読まない — 同じ関数で出す(1 回目の generate でも古い写しにならない)。
      const defaultCss = buildScreenForms(model, ctx).length === 0 ? undefined : renderScreenDefaultCss();
      // 写し元の置き場(ヘッダに出す)。決められない(実装の木が無い)ものは空文字の項目にせず載せない(CSS を読めた = 実装の木がある場面では起きない)。
      const sources = [
        ...(globals === undefined ? [] : stylesheetSource(ctx, GLOBALS_CSS_SOURCE)),
        ...stylesheetSource(ctx, UI_CSS_SOURCE),
        ...(defaultCss === undefined ? [] : screenDefaultCssSource(ctx)),
      ];
      const scoped = [PARTS_DEMO_SCOPE, SCREEN_PREVIEW_SCOPE].flatMap((scope) => [
        ...(globals === undefined ? [] : [scopeCss(globals, scope)]),
        scopeCss(uiCss, scope),
        ...(defaultCss === undefined ? [] : [scopeCss(defaultCss, scope)]),
      ]);
      sections.push({
        file: bookFile(ctx.roots, `assets/ui.css`),
        content: `${[uiCssHeader(sources), '', ...scoped].join('\n')}\n`,
        wholeFile: true,
      });
    }
    return sections;
  },
};
