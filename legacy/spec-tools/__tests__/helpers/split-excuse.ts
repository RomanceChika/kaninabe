/**
 * 行数を理由にした分割の説明を見つける道具(`splitExcuses`)。構造テスト `unit/gates/no-oversize-split-excuse.test.ts`(わざと壊す確認)と、
 * 製品・仕組みの木を歩く側(`dev-repo/unit/gates/no-oversize-split-excuse.test.ts`)が同じものを使う。
 */

/**
 * **「行数の制限のために分けた」と書く分割を残さない**(束 外部レビュー C-③-C2)。
 *
 * 300 行は信号であって上限ではない。ファイルのコメントが**行数を理由に分割を説明している**
 * (「1 ファイル 300 行の制限のために分けた。境界に意味は無い」)なら、それは責務が 1 つなのに行数で
 * 切った印である —— くっつけて宣言(`@oversize` / `@split-review`)で通すか、責務の名前で割り直す。
 * ファイルの説明は**そのファイルの責務**を書く。執行は規約 scripts-code-quality.md の
 * 「行数で割るときは責務の境界で割る」。
 *
 * **見るもの**は、ファイル内の**コメントの文**(冒頭の見出しだけでなく、途中の節のコメントも)で、
 * 次のどれかに当たるもの。
 *
 *   1. **「境界に(仕様上の・設計上の)意味は無い」という断定**(行数の語が無くても、書いた時点で禁止)
 *   2. **ファイルの大きさの制限を理由にした語**(`1 ファイル 300 行` ・`300 行の制限 / 上限 / 超過 / 以内` ・
 *      `ファイル行数` ・`行数の制限 / 都合 / 上限 / 超過 / 関係` ・`行数制限 / 上限` ・`サイズの都合` ・`肥大化` ・
 *      `長くなった` ・`大きくなりすぎた` ・`max-lines`(`max-lines-per-function` は別の規則名なので除く))を含む文のうち、分割を指す語
 *      (`分離` ・`分割` ・`分け` ・`割っ` ・`割る` ・`切り出` ・`別ファイル` ・`続き` ・`続く` ・`帰結` ・`割れ` ・
 *      `分かれ`・`名残`・`当たった`)も持つもの、または 1 ファイルの制限そのものを言うもの
 *
 * **基線を持たない(常に 0 件)** —— 件数を固定して少しずつ減らす形にすると、行数で割った説明が新しく
 * 生えても見えなくなる。行数を指す語だけの文(「依存の向きが行数より先」「併読する行数の上限」)と、
 * 分割を指す語だけの文は見ない。
 */

/** ファイルの大きさの制限を理由にする語(1 ファイルの制限そのもの)。 */
const FILE_LIMIT =
  /(?:1\s*ファイル|ファイル\s*1\s*本)\s*300\s*行|300\s*行(?:の?(?:制限|上限|超過)|以内|に収め)|ファイル行数|行数(?:の(?:制限|都合|上限|超過|関係)|制限|上限|超過)|ファイルサイズ|サイズの(?:都合|制限|上限)|肥大|長くなった|長くなりすぎ|長くなり過ぎ|大きくなった|大きくなりすぎ|大きくなり過ぎ|max-lines(?![\w-])/;

/** 分割を指す語。 */
const SPLITTING = /分離|分割|分け|割っ|割る|切り出|別ファイル|続き|続く|帰結|割れ|分かれ|名残|当たった/;

/** 「境界に意味は無い」という断定(行数の語が無くても、書いた時点で禁止である)。 */
const NO_MEANING = /境界(に|には)(仕様上の|設計上の)?意味(論)?は(無|な)い/;

/**
 * ファイルのコメントを全部集める(ブロックコメントと、連続する行コメント)。
 *
 * @param text ファイルの本文
 * @returns コメントごとの中身(コメントの記号は外し、空白は 1 つに畳む)
 */
export function commentsOf(text: string): readonly string[] {
  const found = text.match(/\/\*[\s\S]*?\*\/|\/\/[^\n]*(?:\n\s*\/\/[^\n]*)*/g) ?? [];
  return found.map((comment) =>
    comment
      .replace(/^\s*(?:\/\*+|\*\/|\*|\/\/+)\s?/gm, '')
      .replace(/\*\/\s*$/, '')
      .replace(/\s+/g, ' ')
      .trim(),
  );
}

/**
 * ファイルのコメントのうち、行数を理由に分割を説明している文を返す。
 *
 * @param text ファイルの本文
 * @returns 該当する文(無ければ空)
 */
export function splitExcuses(text: string): readonly string[] {
  return commentsOf(text)
    .flatMap((comment) => comment.split(/(?<=。)/))
    .filter((sentence) => NO_MEANING.test(sentence) || (FILE_LIMIT.test(sentence) && (SPLITTING.test(sentence) || /(?:1\s*ファイル|ファイル\s*1\s*本)\s*300\s*行/.test(sentence))))
    .map((sentence) => sentence.trim());
}
