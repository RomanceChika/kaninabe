/**
 * 実装のソースを**字面で**突き合わせる検査が共有する前処理 —— コメントと文字列を潰す。
 *
 * この体系には「実装のソースを読んで宣言と突き合わせる」検査が複数ある(K1 の
 * `process.env` 走査・A11 の閉世界・A16 の注釈の中身・X6 の実行時の約束の接地)。
 * 生のソースをそのまま `includes` / 正規表現で見ると、**コメントや文字列の中の字面**が
 * 実装として数えられる —— 独立レビュー(束 ㉑ の 4-A)の実測では、アダプタに
 * `// 正は EXTERNAL_EXPECTATIONS.discord_webhook.timeoutMs` と**書いてあるだけ**で
 * X6 の接地チェックが通った(実装は生の数値に戻っていた)。
 *
 * ここを通すと、コメント・文字列リテラル・テンプレートリテラルは**同じ長さの空白**に
 * 置き換わる(改行だけ残すので行番号と index は元のソースと一致する)。
 *
 * ファイル I/O は行わない(純粋関数)。`lib/io` に置いてあるのは「ソースを読む層の
 * 小道具」だからであり、`paths.ts` と同じ扱いである。
 */

/** ブロックコメント・行コメント・文字列/テンプレートリテラル。 */
const MASKED = /\/\*[\s\S]*?\*\/|\/\/[^\n]*|'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"|`(?:[^`\\]|\\.)*`/g;

/**
 * コメントと文字列を空白に潰す(行番号と index がずれないように改行だけ残す)。
 *
 * @param source ソースの生テキスト
 * @returns 同じ長さの、コメントと文字列が空白になったテキスト
 */
export function maskCode(source: string): string {
  return source.replace(MASKED, (match) => match.replace(/[^\n]/g, ' '));
}
