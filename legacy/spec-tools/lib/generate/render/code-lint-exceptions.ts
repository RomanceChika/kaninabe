/**
 * `exceptions:`(action_spec / query_spec)→ ESLint の免除表(`app/src/domain/generated/lint-exceptions.json`)の生成器。
 *
 * 免除の一本化(決定性の格上げ ⑥ 第2段)。`eslint-disable` はコードに書けない
 * (`layer/no-eslint-disable-comment`)ため、generate で導けない ESLint 違反を受け入れる唯一の口が
 * 仕様側の `exceptions:` 宣言である。`app/eslint.config.mjs` はこの生成物を読み、
 * ファイル単位で該当ルールをオフにする(行単位ではない —— 免除は「そのファイルの、その形の
 * 違反を許す」という粒度に固定し、同じルールの例外が増えたら拡張トリアージに回す)。
 *
 * 出力を `.json` にするのは、ESLint 設定(`app/eslint.config.mjs`、Node 実行の `.mjs`)が
 * TypeScript を経由せずそのまま `import ... with { type: 'json' }` で読めるようにするため
 * (他の生成物と違い、実行時に app 側の TypeScript ビルドを経由しない消費者だけが読む)。
 *
 * 規約どおりファイル I/O はせず、SpecModel から GeneratedSection を返す純粋関数である
 * (scripts-code-quality.md)。
 */

import type { SpecModel } from '../../model/types.js';
import type { LintExceptionDecl } from '../../model/parse-lint-exceptions.js';
import type { DocGenerator, GeneratedSection, GenerateContext } from '../../gen-kit/generator.js';
import { generatedFile } from '../../gen-kit/code-emit.js';
import type { ProductRoots } from '../../model/product/types.js';
import { LAYOUT_DEFINITION_CHECK, placedPath } from '../layout-placement.js';

/** 生成物の出力先(リポジトリルート相対)。app 側は `src/domain/generated/lint-exceptions.json` として読む。 */
const outputFile = (roots: ProductRoots): string => generatedFile(roots, 'lint-exceptions.json');

/**
 * 免除表のファイルの鍵(実装の木の根 `app/` からの相対パス)を、置き場の配置から引く。**製品の根からの相対 `''` で引く**(ESLint の設定が `app/` を根に読むため)。
 * 操作の本体は役割 `operation-logic` の置き場、クエリの写像は役割 `infrastructure` の置き場の代表(集約のクエリの写像ファイル)。
 * 配置が役割を解決できなければ前提の失敗で止める(黙って免除を落とすと、ESLint の違反が緑のまま消える)。名指すのは配置の定義の検査。
 */
function exemptionFile(ctx: GenerateContext, role: 'operation-logic' | 'infrastructure', key: string, what: string, file: string): string {
  return placedPath(ctx.layout, { app: '' }, { role, key, what, location: { file }, verifier: LAYOUT_DEFINITION_CHECK });
}

/** ファイル(app/ からの相対パス)→ ルール ID → 理由。 */
type ExceptionTable = Record<string, Record<string, string>>;

/**
 * 全 action_spec + query_spec の `exceptions:` から免除表を生成するジェネレーター。
 * 出力は `app/src/domain/generated/lint-exceptions.json`(全体生成・JSON なのでヘッダコメントは
 * 持てない —— 先頭の `"$generated"` エントリに由来を記す)。
 */
export const lintExceptionsGenerator: DocGenerator = {
  id: 'code-lint-exceptions',

  generate(_model: SpecModel, ctx: GenerateContext): GeneratedSection[] {
    const table: ExceptionTable = {};

    // 免除は実装の木のファイルへの免除なので、実装の木を持たない製品は表が空(置き場が無いことが事実)。
    const hasApp = ctx.roots.app !== null;

    for (const action of hasApp ? (ctx.actions?.actions ?? []) : []) {
      if (action.exceptions.length === 0) continue;
      const file = exemptionFile(ctx, 'operation-logic', action.handles.raw, `操作 ${action.handles.raw} の本体(ESLint の免除先)`, action.location.file);
      mergeExceptions(table, file, action.exceptions);
    }

    for (const query of hasApp ? (ctx.queries?.queries ?? []) : []) {
      if (query.exceptions.length === 0) continue;
      const directory = query.relPath.split('/')[0] ?? query.source;
      const file = exemptionFile(ctx, 'infrastructure', directory, `クエリ ${query.source} の写像(ESLint の免除先)`, query.location.file);
      mergeExceptions(table, file, query.exceptions);
    }

    return [{ file: outputFile(ctx.roots), content: renderFile(table), wholeFile: true }];
  },
};

/** 1 ファイル分の免除を表に足し込む(同じファイルに複数の仕様が例外を宣言してもよい)。 */
function mergeExceptions(table: ExceptionTable, file: string, exceptions: readonly LintExceptionDecl[]): void {
  const existing = table[file] ?? {};
  for (const decl of exceptions) existing[decl.rule] = decl.reason;
  table[file] = existing;
}

/**
 * JSON ファイル全体を組み立てる。
 *
 * JSON はコメントを持てないため、鮮度と由来は `"$generated"` キー(通常のルール ID とは
 * 衝突しない先頭記号)に埋め込む。
 */
function renderFile(table: ExceptionTable): string {
  const sortedTable: ExceptionTable = {};
  for (const file of Object.keys(table).sort((a, b) => a.localeCompare(b))) {
    const rules = table[file] ?? {};
    const sortedRules: Record<string, string> = {};
    for (const rule of Object.keys(rules).sort((a, b) => a.localeCompare(b))) {
      sortedRules[rule] = rules[rule] ?? '';
    }
    sortedTable[file] = sortedRules;
  }
  const body = {
    $generated: 'AUTO-GENERATED by `npm run generate` — 手編集禁止。正は action_spec / query_spec の exceptions:。',
    ...sortedTable,
  };
  return `${JSON.stringify(body, null, 2)}\n`;
}
